#include <stddef.h>
#include "ThreadsDone.h"


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CThreadsDone::Init(void)
{
	miThreadsStopped.Set(0);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CThreadsDone::ThreadStateChanged(CThread* pcThread, EThreadState eState)
{
	if (eState == TS_Stopped)
	{
		miThreadsStopped.Increment();
	}
}

//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CThreadsDone::Wait(int iCount, int iTimeoutMilliseconds)
{
	return miThreadsStopped.WaitUntilAtLeast(iCount, iTimeoutMilliseconds);
}


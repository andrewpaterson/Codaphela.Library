//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CSafeArrayBlock::MemcpyDestAndUnlock(void* pvSource, void* pvDest)
{
	if (pvSource != NULL)
	{
		memcpy(pvDest, pvSource, c.ElementSize());
		m.Unlock();
		return true;
	}
	else
	{
		m.Unlock();
		return false;
	}
}


#ifdef _WIN32
#include "BaseLib/WindowsHeaders.h"
#include "AtomicInt.h"


static_assert(sizeof(LONG) == sizeof(int), "CAtomicInt needs LONG and int to be the same size.");


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CAtomicInt::Set(int iValue)
{
	InterlockedExchange((volatile LONG*)&miValue, iValue);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Get(void)
{
	return InterlockedCompareExchange((volatile LONG*)&miValue, 0, 0);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Increment(void)
{
	return InterlockedIncrement((volatile LONG*)&miValue);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Decrement(void)
{
	return InterlockedDecrement((volatile LONG*)&miValue);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Add(int iValue)
{
	return InterlockedExchangeAdd((volatile LONG*)&miValue, iValue) + iValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CAtomicInt::CompareExchange(int iExpected, int iValue)
{
	return InterlockedCompareExchange((volatile LONG*)&miValue, iValue, iExpected) == iExpected;
}


#endif // _WIN32


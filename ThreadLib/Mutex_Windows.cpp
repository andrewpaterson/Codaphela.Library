#ifdef _WIN32
#include "BaseLib/WindowsHeaders.h"
#include "Mutex.h"


static_assert(sizeof(SRWLOCK) <= MUTEX_HANDLE_SIZE, "MUTEX_HANDLE_SIZE is too small for an SRWLOCK.");


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMutex::Init(void)
{
	InitializeSRWLock((SRWLOCK*)maMutex);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMutex::Kill(void)
{
	//An SRWLOCK does not need to be destroyed.
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMutex::Lock(void)
{
	AcquireSRWLockExclusive((SRWLOCK*)maMutex);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMutex::Unlock(void)
{
	ReleaseSRWLockExclusive((SRWLOCK*)maMutex);
}


#endif // _WIN32


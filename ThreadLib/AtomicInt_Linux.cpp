#ifdef LINUX_GNU_32
#include "AtomicInt.h"


//Linux has no system calls for atomic operations; these are the GCC builtins.


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CAtomicInt::Set(int iValue)
{
	__atomic_store_n(&miValue, iValue, __ATOMIC_SEQ_CST);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Get(void)
{
	return __atomic_load_n(&miValue, __ATOMIC_SEQ_CST);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Increment(void)
{
	return __atomic_add_fetch(&miValue, 1, __ATOMIC_SEQ_CST);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Decrement(void)
{
	return __atomic_sub_fetch(&miValue, 1, __ATOMIC_SEQ_CST);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CAtomicInt::Add(int iValue)
{
	return __atomic_add_fetch(&miValue, iValue, __ATOMIC_SEQ_CST);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CAtomicInt::CompareExchange(int iExpected, int iValue)
{
	return __atomic_compare_exchange_n(&miValue, &iExpected, iValue, false, __ATOMIC_SEQ_CST, __ATOMIC_SEQ_CST);
}


#endif // LINUX_GNU_32


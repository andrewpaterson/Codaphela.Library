#include "CircuitViewport.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::Init(int32 iWidth, int32 iHeight)
{
	msSize.Init(iWidth, iHeight);
	msPosition.Init(0, 0);
	mfZoom = 1.0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::SetSize(int32 iWidth, int32 iHeight)
{
	msSize.Init(iWidth, iHeight);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SInt32Vec2 CCircuitViewport::GetSize(void)
{
	return msSize;
}


//////////////////////////////////////////////////////////////////////////
//
// The position is in pixels; grid 0, 0 is drawn at the centre of the
// screen plus the position.
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::SetPosition(float64 x, float64 y)
{
	msPosition.Init(x, y);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SFloat64Vec2 CCircuitViewport::GetPosition(void)
{
	return msPosition;
}


//////////////////////////////////////////////////////////////////////////
//
// Moves the view, the circuit moves the other way.
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::Scroll(float64 fRight, float64 fDown)
{
	msPosition.x -= fRight;
	msPosition.y -= fDown;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::SetZoom(float64 fZoom)
{
	if (fZoom < CIRCUIT_MINIMUM_ZOOM)
	{
		fZoom = CIRCUIT_MINIMUM_ZOOM;
	}
	if (fZoom > CIRCUIT_MAXIMUM_ZOOM)
	{
		fZoom = CIRCUIT_MAXIMUM_ZOOM;
	}
	mfZoom = fZoom;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GetZoom(void)
{
	return mfZoom;
}


//////////////////////////////////////////////////////////////////////////
//
// Zooms keeping the grid point under the screen point where it is.
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::ZoomAround(float64 fScreenX, float64 fScreenY, float64 fZoom)
{
	SFloat64Vec2	sScreen;
	SFloat64Vec2	sGrid;
	SFloat64Vec2	sMoved;

	sScreen.Init(fScreenX, fScreenY);
	ScreenToGrid(&sGrid, &sScreen);
	SetZoom(fZoom);
	GridToScreen(&sMoved, &sGrid);
	msPosition.x += sScreen.x - sMoved.x;
	msPosition.y += sScreen.y - sMoved.y;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::GridToScreen(SFloat64Vec2* psScreen, SFloat64Vec2* psGrid)
{
	psScreen->Init(GridToScreenX(psGrid->x), GridToScreenY(psGrid->y));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCircuitViewport::ScreenToGrid(SFloat64Vec2* psGrid, SFloat64Vec2* psScreen)
{
	float64		fScale;

	fScale = GetPixelsPerGrid();
	psGrid->Init((psScreen->x - msSize.x / 2.0 - msPosition.x) / fScale,
				 (psScreen->y - msSize.y / 2.0 - msPosition.y) / fScale);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GridToScreenX(float64 x)
{
	return x * GetPixelsPerGrid() + msSize.x / 2 + msPosition.x;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GridToScreenY(float64 y)
{
	return y * GetPixelsPerGrid() + msSize.y / 2 + msPosition.y;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GetPixelsPerGrid(void)
{
	return CIRCUIT_GRID_SCALE * mfZoom;
}


//////////////////////////////////////////////////////////////////////////
//
// A line fWidth pixels wide at zoom one.  Lines stop getting thinner below
// half zoom.
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GetLineWidth(float64 fWidth)
{
	if (mfZoom < 0.5)
	{
		return 0.5 * fWidth;
	}
	return mfZoom * fWidth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GetDefaultLineWidth(void)
{
	return GetLineWidth(2.0);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GetCircleRadius(void)
{
	if (mfZoom < 0.3)
	{
		return 0.3;
	}
	return mfZoom;
}


//////////////////////////////////////////////////////////////////////////
//
// The radius of the dot drawn on a port and a junction.
//
//////////////////////////////////////////////////////////////////////////
float64 CCircuitViewport::GetConnectionRadius(void)
{
	return GetCircleRadius() * 3;
}


void CCPPToken::Append(CChars* psz, CCPPTokeniser* pcTokeniser)
{
	SPreprocessedToken*	psSource;

	//Tokens print as they were spelled.
	psSource = pcTokeniser->GetSource(this);
	if (psSource)
	{
		psSource->Append(psz);
	}
}



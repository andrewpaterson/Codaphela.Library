//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CDefine::Equals(CDefine* pcOther)
{
	if (pcOther)
	{
		if (IsBracketed() == pcOther->IsBracketed())
		{
			if (mcReplacement.Equals(&pcOther->mcReplacement))
			{
				return true;
			}
		}
	}
	return false;
}



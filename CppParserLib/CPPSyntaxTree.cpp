#include "CPPSyntaxes.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCPPSyntaxTree::Init(CCPPTokeniser* pcTokeniser)
{
	SCPPTokenSymbol*	psTokenSymbols;
	size				uiNumTokens;

	mpcTokeniser = pcTokeniser;
	mcMemory.Init(this);
	mcSymbols.Init();
	mpcRoot = NULL;
	maszErrors.Init();
	maiErrorTokens.Init();

	masTokenSymbols.Init();
	uiNumTokens = pcTokeniser->NumTokens();
	if (uiNumTokens > 0)
	{
		psTokenSymbols = masTokenSymbols.InsertNumAt(uiNumTokens, 0);
		memset(psTokenSymbols, 0, uiNumTokens * sizeof(SCPPTokenSymbol));
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCPPSyntaxTree::Kill(void)
{
	masTokenSymbols.Kill();
	maiErrorTokens.Kill();
	maszErrors.Kill();
	mpcRoot = NULL;
	mcSymbols.Kill();
	mcMemory.Kill();
	mpcTokeniser = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CCPPTokeniser* CCPPSyntaxTree::GetTokeniser(void)
{
	return mpcTokeniser;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CCPPSyntaxMemory* CCPPSyntaxTree::GetMemory(void)
{
	return &mcMemory;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CCPPSymbolTable* CCPPSyntaxTree::GetSymbols(void)
{
	return &mcSymbols;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CCPPSyntaxTranslationUnit* CCPPSyntaxTree::GetRoot(void)
{
	return mpcRoot;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCPPSyntaxTree::SetRoot(CCPPSyntaxTranslationUnit* pcRoot)
{
	mpcRoot = pcRoot;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCPPSyntaxTree::AddError(int iToken, char* szError)
{
	maszErrors.Add(szError);
	maiErrorTokens.Add(iToken);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CCPPSyntaxTree::NumErrors(void)
{
	return maszErrors.NumElements();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CCPPSyntaxTree::GetError(size iIndex)
{
	return maszErrors.GetText(iIndex);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CCPPSyntaxTree::GetErrorToken(size iIndex)
{
	return maiErrorTokens.GetValue(iIndex);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCPPSyntaxTree::SetTokenSymbol(int iToken, CCPPSymbol* pcSymbol, ECPPTokenRole eRole)
{
	SCPPTokenSymbol*	psTokenSymbol;

	psTokenSymbol = masTokenSymbols.SafeGet(iToken);
	if (psTokenSymbol)
	{
		psTokenSymbol->pcSymbol = pcSymbol;
		psTokenSymbol->uiRole = (uint8)eRole;
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SCPPTokenSymbol* CCPPSyntaxTree::GetTokenSymbol(int iToken)
{
	return masTokenSymbols.SafeGet(iToken);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCPPSyntaxTree::PrettyPrint(CChars* pszDest)
{
	if (mpcRoot)
	{
		((CCPPSyntax*)mpcRoot)->PrettyPrint(pszDest, 0);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCPPSyntaxTree::TypePrint(CChars* pszDest)
{
	if (mpcRoot)
	{
		((CCPPSyntax*)mpcRoot)->TypePrint(pszDest, 0);
	}
}


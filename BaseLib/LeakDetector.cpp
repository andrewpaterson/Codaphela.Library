//////////////////////////////////////////////////////////////////////////
void BreakOnAllocation(long iAllocation)
{
#ifdef _MSC_VER
	_CrtSetBreakAlloc(iAllocation);
#endif // _MSC_VER
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void LeakDetection(void)
{
#ifdef _MSC_VER
	_CrtDumpMemoryLeaks();
#endif // _MSC_VER
#ifdef __SANITIZE_ADDRESS__
	__lsan_do_leak_check();
#endif // __SANITIZE_ADDRESS__
}


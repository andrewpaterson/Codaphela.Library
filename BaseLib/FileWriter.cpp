//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CFileWriter::WriteLittleEndianInt32(uint32 ui)
{
	uint8	aui[4];

	aui[0] = (uint8)ui;
	aui[1] = (uint8)(ui >> 8);
	aui[2] = (uint8)(ui >> 16);
	aui[3] = (uint8)(ui >> 24);
	CheckWrite(aui, 4);
	return true;
}



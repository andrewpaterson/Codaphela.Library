//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CFileWriter::WriteLittleEndianInt16(uint16 ui)
{
	uint8	aui[2];

	aui[0] = (uint8)ui;
	aui[1] = (uint8)(ui >> 8);
	CheckWrite(aui, 2);
	return true;
}



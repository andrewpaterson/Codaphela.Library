//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CFileWriter::WriteSize(lsize ui)
{
	uint32	ui32;

	//Sizes are written as four bytes so files are the same in 32 and 64 bit builds.  ReadSize sign extends them so a
	//size that has wrapped below zero (such as MAX_SIZE) reads back the same in a 64 bit build.  A 64 bit build cannot
	//write a size that would not read back.
	ui32 = (uint32)ui;
	if ((lsize)(ptrdiff)(int32)ui32 != ui)
	{
		return false;
	}
	CheckWrite(&ui32, sizeof(uint32));
	return true;
}


#ifndef SIZE_IS_LSIZE
//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CFileWriter::WriteSize(size ui)
{
	if (ui == MAX_SIZE)
	{
		return WriteSize(MAX_LSIZE);
	}
	return WriteSize((lsize)ui);
}
#endif // SIZE_IS_LSIZE


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CFileWriter::WriteSizes(size* pai, size iLength)
{
	size	i;

	for (i = 0; i < iLength; i++)
	{
		if (!WriteSize(pai[i]))
		{
			return false;
		}
	}
	return true;
}



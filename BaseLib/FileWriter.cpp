//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CFileWriter::WriteString(const char* szString)
{
	size	iStrLen;

	iStrLen = strlen(szString)+1;
	WriteSize(iStrLen);
	CheckWrite(szString, iStrLen);
	return true;
}



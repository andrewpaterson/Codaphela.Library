void CValueSequenceConfig::Init(const char* szDirectory, EDurableSync eSync, size uiBlockSize)
{
	mszDirectory = szDirectory;
	meSync = eSync;
	muiBlockSize = uiBlockSize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CValueSequenceConfig::Kill(void)
{
	CSequenceConfig::Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
const char* CValueSequenceConfig::Getdirectory(void)
{
	return mszDirectory;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
EDurableSync CValueSequenceConfig::GetSync(void)
{
	return meSync;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CValueSequenceConfig::GetBlockSize(void)
{
	return muiBlockSize;
}



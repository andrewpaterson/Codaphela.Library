#include "IndexTreeIterator.h"



//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CIndexTreeIterator::Init(uint32 iType)
{
	miType = iType;
	mbStarted = false;
	macKey.Init();
	Clear();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CIndexTreeIterator::Kill(void)
{
	miType = 0;
	mbStarted = false;
	Clear();
	macKey.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CIndexTreeIterator::GetDataSize(void)
{
	return miDataSize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void* CIndexTreeIterator::GetData(void)
{
	return macData;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CIndexTreeIterator::GetKeySize(void)
{
	return miKeySize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint8* CIndexTreeIterator::GetKey(void)
{
	return macKey.GetData();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CIndexTreeIterator::Clear(void)
{
	if (macKey.IsEmbedded() || macKey.IsArray())
	{
		macKey.Resize(0);
	}
	memset(macData, 0, MAX_DATA_SIZE);
	miDataSize = 0;
	miKeySize = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CIndexTreeIterator::SetKey(uint8* pvKey, size uiKeySize)
{
	//Ended by a zero: GetKey is often used as a string.
	macKey.Resize(uiKeySize + 1);
	memcpy(macKey.GetData(), pvKey, uiKeySize);
	macKey.GetData()[uiKeySize] = 0;
}


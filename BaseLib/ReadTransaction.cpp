OIndex CReadTransaction::StartIndexIteration(SIndexTreeFileIterator* psIterator, void* pvData, lsize* piDataSize, lsize iMaxDataSize)
{
	//The transaction iterates its own snapshot; the iterator is only made safe to Kill.
	psIterator->Init();
	mpcCodabase->SnapshotIndices(miSnapshot, mcIteration.StartIndices());
	mcIteration.SortIndices();
	return IndexIterate(psIterator, pvData, piDataSize, iMaxDataSize);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
OIndex CReadTransaction::IndexIterate(SIndexTreeFileIterator* psIterator, void* pvData, lsize* piDataSize, lsize iMaxDataSize)
{
	OIndex	oi;
	lsize	uiDataSize;

	while (mcIteration.NextIndex(&oi))
	{
		if (Get(oi, &uiDataSize, pvData, (size)iMaxDataSize))
		{
			SafeAssign(piDataSize, (size)uiDataSize);
			return oi;
		}
	}
	return INVALID_O_INDEX;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CReadTransaction::StartNameIteration(SIndexTreeFileIterator* psIterator, char* szKey, OIndex* poi)
{
	//The transaction iterates its own snapshot; the iterator is only made safe to Kill.
	psIterator->Init();
	mpcCodabase->SnapshotNames(miSnapshot, mcIteration.StartNames());
	mcIteration.SortNames();
	return NameIterate(psIterator, szKey, poi);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CReadTransaction::NameIterate(SIndexTreeFileIterator* psIterator, char* szKey, OIndex* poi)
{
	char*	szName;
	OIndex	oi;

	for (;;)
	{
		szName = mcIteration.NextName();
		if (szName == NULL)
		{
			break;
		}

		oi = GetIndex(szName);
		if (oi != INVALID_O_INDEX)
		{
			if (szKey)
			{
				StrCpySafe(szKey, szName, MAX_KEY_SIZE);
			}
			SafeAssign(poi, oi);
			return true;
		}
	}

	//As the store does: the index is set to INVALID_O_INDEX at the end, and some callers only test that.
	SafeAssign(poi, INVALID_O_INDEX);
	return false;
}


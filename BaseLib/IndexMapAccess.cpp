#include "IndexMapIterator.h"
#include "IndexBlock.h"
#include "IndexMapAccess.h"


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CIndexMapAccess::Init(CIndexBlock* pcIndex)
{
	mpcIndex = pcIndex;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CIndexMapAccess::Kill(void)
{
	mpcIndex = NULL;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
int64 CIndexMapAccess::NumElements(void)
{
	return mpcIndex->NumElements();
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CIndexMapAccess::Dump(void)
{
	mpcIndex->Dump();
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
CMapIterator* CIndexMapAccess::CreateIterator(void)
{
	CIndexMapIterator* pcIter;

	pcIter = NewMalloc<CIndexMapIterator>();
	pcIter->Init(mpcIndex);

	return pcIter;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CIndexMapAccess::FreeIterator(CMapIterator* pcIter)
{
	SafeKill(pcIter);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void* CIndexMapAccess::Put(const void* pvKey, size iKeySize, const void* pvData, size uiDataSize)
{
	void* pv;

	pv = mpcIndex->Put((uint8*)pvKey, iKeySize, uiDataSize);
	if (pv)
	{
		memcpy(pv, pvData, uiDataSize);
		return pv;
	}
	else
	{
		return NULL;
	}
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void* CIndexMapAccess::Get(const void* pvKey, size iKeySize, size* puiDataSize)
{
	bool	bResult;
	void* pvData;

	bResult = mpcIndex->Get((uint8*)pvKey, iKeySize, &pvData, puiDataSize);
	if (bResult)
	{
		return pvData;
	}
	else
	{
		return NULL;
	}
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
size CIndexMapAccess::DataSize(void* pvKey, size iKeySize)
{
	return mpcIndex->DataSize((uint8*)pvKey, iKeySize);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CIndexMapAccess::Remove(const void* pvKey, size iKeySize)
{
	return mpcIndex->Remove((uint8*)pvKey, iKeySize);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CIndexMapAccess::Has(const void* pvKey, size iKeySize)
{
	return mpcIndex->HasKey((uint8*)pvKey, iKeySize);
}


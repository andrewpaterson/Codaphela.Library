#include "Logger.h"
#include "MemoryCacheDescriptor.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void SMemoryCacheDescriptor::SetNext(SMemoryCacheDescriptor* psNext)
{
	if (psNext == NULL)
	{
		gcLogger.Error2(__METHOD__, " Next may not be NULL.", NULL);
	}
	mpsNext = psNext;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void SMemoryCacheDescriptor::SetPrev(SMemoryCacheDescriptor* psPrev)
{
	if (psPrev == NULL)
	{
		gcLogger.Error2(__METHOD__, " Prev may not be NULL.", NULL);
	}
	mpsPrev = psPrev;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void SMemoryCacheDescriptor::SetSize(size iSize)
{
	if (iSize == 0)
	{
		gcLogger.Error2(__METHOD__, " Size may not be 0.", NULL);
	}

	miSize = iSize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void SMemoryCacheDescriptor::Clear(void)
{
	mpsNext = NULL;
	mpsPrev = NULL;
	miSize = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void SMemoryCacheDescriptor::ClearNext(void)
{
	mpsNext = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void SMemoryCacheDescriptor::ClearPrev(void)
{
	mpsPrev = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size SMemoryCacheDescriptor::GetSize(void)
{
	return miSize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool SMemoryCacheDescriptor::IsSize(size iSize)
{
	return miSize == iSize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool SMemoryCacheDescriptor::IsPrev(SMemoryCacheDescriptor* psDesc)
{
	return mpsPrev == psDesc;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool SMemoryCacheDescriptor::IsNext(SMemoryCacheDescriptor* psDesc)
{
	return mpsNext == psDesc;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SMemoryCacheDescriptor* SMemoryCacheDescriptor::GetNext(void)
{
	return mpsNext;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SMemoryCacheDescriptor* SMemoryCacheDescriptor::GetPrev(void)
{
	return mpsPrev;
}


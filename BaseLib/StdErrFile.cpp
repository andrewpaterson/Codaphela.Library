#include <stdio.h>
#include "ConstructorCall.h"
#include "StdErrFile.h"


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CStdErrFile::Init(void)
{
	CAbstractFile::Init();
	miPos = 0;
	mbOpen = false;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CStdErrFile::Kill(void)
{
	miPos = 0;
	mbOpen = false;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CStdErrFile::Open(EFileMode eFileMode)
{
	mbOpen = true;
	return true;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CStdErrFile::Close(void)
{
	fflush(stderr);
	mbOpen = false;
	return true;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
size CStdErrFile::Read(void* pvBuffer, size iSize, size iCount)
{
	return 0;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CStdErrFile::Seek(filePos iOffset, EFileSeekOrigin iSeekOrigin)
{
	if (iSeekOrigin == EFSO_END)
	{
		if (iOffset == 0)
		{
			return true;
		}
	}
	return false;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
size CStdErrFile::Write(const void* pvBuffer, size iSize, size iCount)
{
	size	iWritten;

	iWritten = fwrite(pvBuffer, iSize, iCount, stderr);
	miPos += iWritten * iSize;
	return iWritten;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
filePos CStdErrFile::Tell(void)
{
	return miPos;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CStdErrFile::IsOpen(void)
{
	return mbOpen;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
filePos CStdErrFile::Size(void)
{
	return miPos;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CStdErrFile::Truncate(filePos iSize)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CStdErrFile::Flush(void)
{
	return fflush(stderr) == 0;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CStdErrFile::Delete(void)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
char* CStdErrFile::GetFilename(void)
{
	return (char*)"StdErr";
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
CStdErrFile* StdErrFile(void)
{
	CStdErrFile*	pcStdErrFile;

	pcStdErrFile = NewMalloc<CStdErrFile>();
	pcStdErrFile->Init();
	pcStdErrFile->mbBasicFileMustFree = true;
	return pcStdErrFile;
}


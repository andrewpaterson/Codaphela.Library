#include "StringHelper.h"
#include "PointerFunctions.h"
#include "TransactionIteration.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTransactionIteration::Init(void)
{
	maoiIndices.Init();
	miIndexPosition = 0;
	maszNames.Init();
	miNamePosition = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTransactionIteration::Kill(void)
{
	maszNames.Kill();
	maoiIndices.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CArrayOIndex* CTransactionIteration::StartIndices(void)
{
	maoiIndices.ReInit();
	miIndexPosition = 0;
	return &maoiIndices;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTransactionIteration::SortIndices(void)
{
	maoiIndices.QuickSort();
	maoiIndices.RemoveDuplicatesFromSorted();
	miIndexPosition = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTransactionIteration::NextIndex(OIndex* poi)
{
	if (miIndexPosition >= maoiIndices.NumElements())
	{
		return false;
	}
	*poi = maoiIndices.GetValue(miIndexPosition);
	miIndexPosition++;
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CArrayChars* CTransactionIteration::StartNames(void)
{
	maszNames.ReInit();
	miNamePosition = 0;
	return &maszNames;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTransactionIteration::SortNames(void)
{
	size	i;

	maszNames.QuickSort();
	i = maszNames.NumElements();
	while (i > 1)
	{
		i--;
		if (maszNames.Get(i)->Equals(maszNames.GetText(i - 1)))
		{
			maszNames.Remove(i);
		}
	}
	miNamePosition = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CTransactionIteration::NextName(void)
{
	char*	szName;

	if (miNamePosition >= maszNames.NumElements())
	{
		return NULL;
	}
	szName = maszNames.GetText(miNamePosition);
	miNamePosition++;
	return szName;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CopyTransactionName(CChars* pszName, bool bFound, char* szName, uint32* puiNameLength, uint32 uiMaxNameLength)
{
	//The char* form of GetName for the transactions, which find names as CChars.
	if (bFound)
	{
		StrCpySafe(szName, pszName->Text(), uiMaxNameLength);
		SafeAssign(puiNameLength, (uint32)pszName->Length());
	}
	else
	{
		szName[0] = '\0';
		SafeAssign(puiNameLength, 0);
	}
	return bFound;
}


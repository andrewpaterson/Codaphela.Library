//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMenuBarItem::IsMenuOpen(void)
{
	return mpMenuBar->GetOpenItem() == Ptr<CMenuBarItem>(this);
}


//////////////////////////////////////////////////////////////////////////
//
// Moving along the bar while one of its menus is open opens this one.
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::MovedInto(void)
{
	CButton::MovedInto();
	if (mpMenuBar->GetOpenItem().IsNotNull() && !IsMenuOpen())
	{
		mpMenuBar->OpenMenu(this, false);
	}
}


//////////////////////////////////////////////////////////////////////////
//
// The press has already given the button focus.  Unlike a button nothing
// happens on the release.
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::ActivateComponent(int x, int y)
{
	if (IsMenuOpen())
	{
		mpMenuBar->CloseMenu();
	}
	else
	{
		mpMenuBar->OpenMenu(this, false);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::ExecuteComponent(int x, int y)
{
}


//////////////////////////////////////////////////////////////////////////
//
// The keys open the menu with its first item selected.
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::Space(bool bInsert)
{
	mpMenuBar->OpenMenu(this, true);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::Enter(void)
{
	mpMenuBar->OpenMenu(this, true);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::Down(void)
{
	mpMenuBar->OpenMenu(this, true);
}


//////////////////////////////////////////////////////////////////////////
//
// With no menu open left and right move along the bar.
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::Left(void)
{
	mpMenuBar->FocusAdjacentItem(this, -1);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::Right(void)
{
	mpMenuBar->FocusAdjacentItem(this, 1);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMenuBarItem::PopupClosed(Ptr<CComponent> pContent)
{
	if (pContent == mpMenu)
	{
		mpMenuBar->MenuClosed(this);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
Ptr<CMenuContainer> CMenuBarItem::GetMenu(void) { return mpMenu; }


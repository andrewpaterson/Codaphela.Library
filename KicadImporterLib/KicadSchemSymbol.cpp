void CKicadSchemSymbol::Init(char* szLibId)
{
	mszLibId.Init(szLibId);
	mszLibName.Init();
	mszUuid.Init();
	msPosition.Init();
	mfAngle = 0.0;
	meMirror = KSM_None;
	miUnit = 1;
	miBodyStyle = 1;
	mbInBom = true;
	mbOnBoard = true;
	mbDoNotPopulate = false;
	mcProperties.Init();
	macInstances.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemSymbol::Kill(void)
{
	size	i;
	size	uiNumElements;

	uiNumElements = macInstances.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		GetInstance(i)->Kill();
	}
	macInstances.Kill();
	mcProperties.Kill();
	mszUuid.Kill();
	mszLibName.Kill();
	mszLibId.Kill();
}



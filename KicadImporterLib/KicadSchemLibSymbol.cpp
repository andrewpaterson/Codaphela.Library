//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CKicadSchemLibPin* CKicadSchemLibSymbol::GetPin(char* szNumber, int32 iUnit, int32 iBodyStyle)
{
	size				i;
	size				uiNumElements;
	CKicadSchemLibPin*	pcPin;

	uiNumElements = macPins.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		pcPin = GetPin(i);
		if (pcPin->IsOn(iUnit, iBodyStyle) && (StringCompare(pcPin->GetNumber(), szNumber) == 0))
		{
			return pcPin;
		}
	}
	return NULL;
}


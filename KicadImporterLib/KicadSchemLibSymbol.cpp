#include "BaseLib/StringHelper.h"
#include "KicadSchemLibSymbol.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibSymbol::Init(char* szName)
{
	mszName.Init(szName);
	mszExtends.Init();
	mcProperties.Init();
	macPins.Init();
	mbPower = false;
	mbPinNamesHidden = false;
	mbPinNumbersHidden = false;
	miNumUnits = 1;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibSymbol::Kill(void)
{
	size	i;
	size	uiNumElements;

	uiNumElements = macPins.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		GetPin(i)->Kill();
	}
	macPins.Kill();
	mcProperties.Kill();
	mszExtends.Kill();
	mszName.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CKicadSchemLibPin* CKicadSchemLibSymbol::AddPin(EKicadSchemPinType eType, char* szGraphicStyle, int32 iUnit, int32 iBodyStyle)
{
	CKicadSchemLibPin*	pcPin;

	pcPin = (CKicadSchemLibPin*)macPins.Add(sizeof(CKicadSchemLibPin));
	pcPin->Init(eType, szGraphicStyle, iUnit, iBodyStyle);
	if (iUnit > miNumUnits)
	{
		miNumUnits = iUnit;
	}
	return pcPin;
}



#include "KicadSchemLibPin.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibPin::Init(EKicadSchemPinType eType, char* szGraphicStyle, int32 iUnit, int32 iBodyStyle)
{
	meType = eType;
	mszGraphicStyle.Init(szGraphicStyle);
	mszName.Init();
	mszNumber.Init();
	msPosition.Init();
	mfAngle = 0.0;
	mfLength = 0.0;
	mbHidden = false;
	miUnit = iUnit;
	miBodyStyle = iBodyStyle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibPin::Kill(void)
{
	mszNumber.Kill();
	mszName.Kill();
	mszGraphicStyle.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibPin::SetName(char* szName)
{
	mszName.Set(szName);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibPin::SetNumber(char* szNumber)
{
	mszNumber.Set(szNumber);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibPin::SetPosition(SKicadSchemPoint* psPosition, float64 fAngle)
{
	msPosition = *psPosition;
	mfAngle = fAngle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibPin::SetLength(float64 fLength)
{
	mfLength = fLength;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLibPin::SetHidden(bool bHidden)
{
	mbHidden = bHidden;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
EKicadSchemPinType CKicadSchemLibPin::GetType(void)
{
	return meType;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CKicadSchemLibPin::GetGraphicStyle(void)
{
	return mszGraphicStyle.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CKicadSchemLibPin::GetName(void)
{
	return mszName.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CKicadSchemLibPin::GetNumber(void)
{
	return mszNumber.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SKicadSchemPoint* CKicadSchemLibPin::GetPosition(void)
{
	return &msPosition;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CKicadSchemLibPin::GetAngle(void)
{
	return mfAngle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CKicadSchemLibPin::GetLength(void)
{
	return mfLength;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CKicadSchemLibPin::IsHidden(void)
{
	return mbHidden;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int32 CKicadSchemLibPin::GetUnit(void)
{
	return miUnit;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int32 CKicadSchemLibPin::GetBodyStyle(void)
{
	return miBodyStyle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CKicadSchemLibPin::IsOn(int32 iUnit, int32 iBodyStyle)
{
	return ((miUnit == 0) || (miUnit == iUnit)) && ((miBodyStyle == 0) || (miBodyStyle == iBodyStyle));
}


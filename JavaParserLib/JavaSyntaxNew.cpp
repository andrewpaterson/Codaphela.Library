#include "JavaSyntaxNew.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CJavaSyntaxNew::Init(CJavaSyntaxTree* pcTree, CJavaSyntax* pcParent)
{
	CJavaSyntaxExpressionCommon::Init(pcTree, pcParent);
	mpcType = NULL;
	mapcArguments.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CJavaSyntaxNew::Kill(void)
{
	mapcArguments.Kill();
	mpcType = NULL;
	CJavaSyntaxExpressionCommon::Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CJavaSyntaxNew::GetType(void)
{
	return "New";
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CJavaSyntaxNew::TypePrint(CChars* pszDest, int iDepth)
{
	CJavaSyntaxExpressionCommon::TypePrint(pszDest, iDepth);
	pszDest->AppendNewLine();

	if (mpcType)
	{
		mpcType->TypePrint(pszDest, iDepth + 1);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CJavaSyntaxNew::PrettyPrint(CChars* pszDest, int iBlockDepth)
{
	size							i;
	CJavaSyntaxExpressionCommon*	pcArgument;
	size							uiNumElements;

	pszDest->Append("new ");
	if (mpcType)
	{
		mpcType->PrettyPrint(pszDest);
	}

	pszDest->Append('(');
	uiNumElements = mapcArguments.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		if (i != 0)
		{
			pszDest->Append(", ");
		}
		pcArgument = mapcArguments.GetPtr(i);
		pcArgument->PrettyPrint(pszDest, iBlockDepth);
	}
	pszDest->Append(')');
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CJavaSyntaxNew::IsNew(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CJavaSyntaxNew::IsCompoundStatement(void)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CJavaSyntaxNew::SetType(CJavaSyntaxType* pcType) { mpcType = pcType; }
CJavaSyntaxType* CJavaSyntaxNew::GetNewType(void) { return mpcType; }
void CJavaSyntaxNew::AddArgument(CJavaSyntaxExpressionCommon* pcArgument) { mapcArguments.Add(pcArgument); }
CExpressionArray* CJavaSyntaxNew::GetArguments(void) { return &mapcArguments; }


#include "65C64Pins.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::Init(CLogicBus* pcAddress, CLogicBus* pcData, CLogicSignal* pcPHI2, CLogicSignal* pcRESB, CLogicSignal* pcRWB)
{
	size	i;

	mpcAddress = pcAddress;
	mpcData = pcData;
	mpcPHI2 = pcPHI2;
	mpcRESB = pcRESB;
	mpcRWB = pcRWB;
	mpcLowerByte = NULL;
	mpcUpperByte = NULL;
	mpcOPV = NULL;
	mpcVPA = NULL;
	mpcVDA = NULL;
	mpcVPB = NULL;
	for (i = 0; i < NUM_65C64_EDGE_INTERRUPTS; i++)
	{
		mapcEIRQB[i] = NULL;
	}
	mpcLIRQB = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::SetByteTraces(CLogicSignal* pcLowerByte, CLogicSignal* pcUpperByte)
{
	mpcLowerByte = pcLowerByte;
	mpcUpperByte = pcUpperByte;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::SetValidTraces(CLogicSignal* pcOPV, CLogicSignal* pcVPA, CLogicSignal* pcVDA, CLogicSignal* pcVPB)
{
	mpcOPV = pcOPV;
	mpcVPA = pcVPA;
	mpcVDA = pcVDA;
	mpcVPB = pcVPB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::SetInterruptTraces(CLogicSignal* pcEIRQB0, CLogicSignal* pcEIRQB1, CLogicSignal* pcEIRQB2, CLogicSignal* pcEIRQB3, CLogicSignal* pcLIRQB)
{
	mapcEIRQB[0] = pcEIRQB0;
	mapcEIRQB[1] = pcEIRQB1;
	mapcEIRQB[2] = pcEIRQB2;
	mapcEIRQB[3] = pcEIRQB3;
	mpcLIRQB = pcLIRQB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::Kill(void)
{
	size	i;

	mpcAddress = NULL;
	mpcData = NULL;
	mpcPHI2 = NULL;
	mpcRESB = NULL;
	mpcRWB = NULL;
	mpcLowerByte = NULL;
	mpcUpperByte = NULL;
	mpcOPV = NULL;
	mpcVPA = NULL;
	mpcVDA = NULL;
	mpcVPB = NULL;
	for (i = 0; i < NUM_65C64_EDGE_INTERRUPTS; i++)
	{
		mapcEIRQB[i] = NULL;
	}
	mpcLIRQB = NULL;
}



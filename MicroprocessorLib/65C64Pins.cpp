#include "65C64Pins.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::Init(C65MetaBus32* pcAddress, C65MetaBus16* pcData, C65MetaTrace* pcPHI2, C65MetaTrace* pcRESB, C65MetaTrace* pcRWB)
{
	size	i;

	mpcAddress = pcAddress;
	mpcData = pcData;
	mpcPHI2 = pcPHI2;
	mpcRESB = pcRESB;
	mpcRWB = pcRWB;
	mpcLowerByte = NULL;
	mpcUpperByte = NULL;
	mpcOPV = NULL;
	mpcVPA = NULL;
	mpcVDA = NULL;
	mpcVPB = NULL;
	for (i = 0; i < NUM_65C64_EDGE_INTERRUPTS; i++)
	{
		mapcEIRQB[i] = NULL;
	}
	mpcLIRQB = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::SetByteTraces(C65MetaTrace* pcLowerByte, C65MetaTrace* pcUpperByte)
{
	mpcLowerByte = pcLowerByte;
	mpcUpperByte = pcUpperByte;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::SetValidTraces(C65MetaTrace* pcOPV, C65MetaTrace* pcVPA, C65MetaTrace* pcVDA, C65MetaTrace* pcVPB)
{
	mpcOPV = pcOPV;
	mpcVPA = pcVPA;
	mpcVDA = pcVDA;
	mpcVPB = pcVPB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::SetInterruptTraces(C65MetaTrace* pcEIRQB0, C65MetaTrace* pcEIRQB1, C65MetaTrace* pcEIRQB2, C65MetaTrace* pcEIRQB3, C65MetaTrace* pcLIRQB)
{
	mapcEIRQB[0] = pcEIRQB0;
	mapcEIRQB[1] = pcEIRQB1;
	mapcEIRQB[2] = pcEIRQB2;
	mapcEIRQB[3] = pcEIRQB3;
	mpcLIRQB = pcLIRQB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void C65C64Pins::Kill(void)
{
	size	i;

	mpcAddress = NULL;
	mpcData = NULL;
	mpcPHI2 = NULL;
	mpcRESB = NULL;
	mpcRWB = NULL;
	mpcLowerByte = NULL;
	mpcUpperByte = NULL;
	mpcOPV = NULL;
	mpcVPA = NULL;
	mpcVDA = NULL;
	mpcVPB = NULL;
	for (i = 0; i < NUM_65C64_EDGE_INTERRUPTS; i++)
	{
		mapcEIRQB[i] = NULL;
	}
	mpcLIRQB = NULL;
}



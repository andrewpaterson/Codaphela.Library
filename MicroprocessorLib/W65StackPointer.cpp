#include "W65CCore.h"
#include "W65StackPointer.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65StackPointer::Init(void)
{
	Init(SPM_Page);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65StackPointer::Init(EStackPointerMode eMode)
{
	meMode = eMode;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65StackPointer::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int32 CW65StackPointer::GetOffset(CW65CCore* pcCPU)
{
	uint16	uiStackPointer;

	if (meMode == SPM_Linear)
	{
		return pcCPU->GetStackPointer16Bit();
	}

	uiStackPointer = pcCPU->GetStackPointer();
	if (meMode == SPM_PagePlusOne)
	{
		if (pcCPU->IsEmulation())
		{
			return 0x100 | GetLowByte(uiStackPointer + 1);
		}
		else
		{
			return uiStackPointer + 1;
		}
	}
	return uiStackPointer;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65StackPointer::Print(CChars* psz)
{
	if (meMode == SPM_PagePlusOne)
	{
		psz->Append("S+1");
	}
	else
	{
		psz->Append("S");
	}
}


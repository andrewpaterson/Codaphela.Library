//
//////////////////////////////////////////////////////////////////////////
void CW65IRQVector::Init(void)
{
    CW65InterruptVector::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CW65IRQVector::GetAddress(CW65CCore* pcCPU)
{
    if (pcCPU->IsEmulation())
    {
        return 0xfffe;
    }
    else
    {
        return 0xffee;
    }
}


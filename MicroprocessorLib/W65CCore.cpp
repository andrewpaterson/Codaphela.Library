void CW65CCore::WriteProcessorStatus(bool bBreak)
{
	//Software interrupts (BRK, COP) push B set, hardware interrupts push it clear.
	SetIOData(GetPushedProcessorRegisterValue(bBreak));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint8 CW65CCore::GetPushedProcessorRegisterValue(bool bBreak)
{
	uint8	uiValue;

	uiValue = GetProcessorRegisterValue();
	if (IsEmulation())
	{
		//Software interrupts and PHP push B set, hardware interrupts push it clear.
		if (bBreak)
		{
			uiValue |= STATUS_BREAK;
		}
		else
		{
			uiValue &= ~STATUS_BREAK;
		}
	}
	return uiValue;
}



//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CCore::Cycle(CW65CCore* pcCPU)
{
	if (mbNextInstruction)
	{
		miNextCycle = 0;
		mbNextInstruction = false;
		NextInstruction();
	}

	miCycle = miNextCycle;
	NextCycle();
	UpdateBusCycle();
	while (!mpcBusCycle->MustExecute(pcCPU))
	{
		miCycle = miNextCycle;
		NextCycle();
		UpdateBusCycle();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CCore::ExecuteInitialSideOperation(CW65CCore* pcCPU)
{
	CW65BusCycle*			pcBusCycle;
	CW65OperationArray*	pcOperations;
	size				uiNumElements;
	size				i;
	CW65Operation*			pcOperation;

	pcBusCycle = GetBusCycle();
	pcOperations = pcBusCycle->GetOperations();
	uiNumElements = pcOperations->NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		pcOperation = pcOperations->GetPtr(i);
		if (pcOperation->IsInitialSide())
		{
			pcOperation->Execute(pcCPU);
		}
	}
}



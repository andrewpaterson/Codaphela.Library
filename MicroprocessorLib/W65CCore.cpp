//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CCore::GetOpcodeValueHex(CChars* psz, int cycle, CW65Instruction* pcInstruction, bool bAppend0x)
{
    uint16  uiCode;

    if (cycle != 0)
    {
        uiCode = pcInstruction->GetCode();
        if (uiCode <= 255)
        {
            Append0x(psz, bAppend0x);
            To8BitHexString(psz, (uint8)uiCode);
        }
        else
        {
            if (bAppend0x)
            {
                psz->Append("-----");
            }
            else
            {
                psz->Append("---");
            }
        }
    }
    else
    {
        if (bAppend0x)
        {
            psz->Append("#####");
        }
        else
        {
            psz->Append("###");
        }
    }
}



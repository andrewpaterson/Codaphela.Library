#include "W65CCore.h"
#include "BranchAddress.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBranchAddress::Init(void)
{
	Init(BA_Origin);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBranchAddress::Init(EBranchAddress eAddress)
{
	meAddress = eAddress;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBranchAddress::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int32 CBranchAddress::GetOffset(CW65CCore* pcCPU)
{
	uint16	uiTarget;
	uint16	uiOrigin;

	uiTarget = pcCPU->GetProgramCounter()->GetOffset();
	uiOrigin = uiTarget - pcCPU->GetData8BitOffset();
	if (meAddress == BA_Origin)
	{
		return uiOrigin;
	}
	else
	{
		return (uiOrigin & 0xFF00) | (uiTarget & 0x00FF);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBranchAddress::Print(CChars* psz)
{
	if (meAddress == BA_Origin)
	{
		psz->Append("PC-RL");
	}
	else
	{
		psz->Append("PCH-RL,PCL");
	}
}


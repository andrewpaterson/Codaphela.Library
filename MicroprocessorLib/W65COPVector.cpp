void CW65COPVector::Init(void)
{
    CW65InterruptVector::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CW65COPVector::GetAddress(CW65CCore* pcCPU)
{
    if (pcCPU->IsEmulation())
    {
        return 0xfff4;
    }
    else
    {
        return 0xffe4;
    }
}


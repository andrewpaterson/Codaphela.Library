#include "W65CCore.h"
#include "W65DoneInstructionIf8Bit.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIf8Bit::Init(EWidthFromRegister eWidth)
{
    CW65Operation::Init();

    meWidth = eWidth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIf8Bit::Execute(CW65CCore* pcCPU)
{
    if (meWidth == WFR_M)
    {
        pcCPU->DoneIfMemory8Bit();
    }
    else if (meWidth == WFR_XY)
    {
        pcCPU->DoneIfIndex8Bit();
    }
    else
    {
        LOG_ERROR("Unknown Width.");
    }
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DoneInstructionIf8Bit::IsInitialSide(void)
{
    return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIf8Bit::Print(CChars* psz)
{
	psz->Append("DONE_If_8Bit_");
	psz->Append(CW65WidthFromRegister::GetName(meWidth));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CW65DoneInstructionIf8Bit::GetDone8(void)
{
    return 1;
}


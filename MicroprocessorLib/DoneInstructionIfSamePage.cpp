#include "W65CCore.h"
#include "DoneInstructionIfSamePage.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfSamePage::Init(void)
{
	COperation::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfSamePage::Execute(CW65CCore* pcCPU)
{
	//A taken branch finishes here unless it crosses a page (emulation mode, see NoteSix).
	if (!pcCPU->NoteSix())
	{
		pcCPU->DoneInstruction();
	}
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CDoneInstructionIfSamePage::IsInitialSide(void)
{
	return false;
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfSamePage::Print(CChars* psz)
{
	psz->Append("DONE_If_Same_Page");
}


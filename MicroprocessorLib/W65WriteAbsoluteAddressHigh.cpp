#include "W65CCore.h"
#include "W65WriteAbsoluteAddressHigh.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65WriteAbsoluteAddressHigh::Init(void)
{
	CW65DataOperation::Init(false, true, true, false, true);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65WriteAbsoluteAddressHigh::Execute(CW65CCore* pcCPU)
{
	pcCPU->SetIOData(pcCPU->GetAddress()->GetOffsetHigh());
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65WriteAbsoluteAddressHigh::IsInitialSide(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65WriteAbsoluteAddressHigh::Print(CChars* psz)
{
	psz->Append("Write(AAH)");
}


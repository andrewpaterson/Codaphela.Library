#include "W65DataOperation.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DataOperation::Init(bool bValidProgramAddress, bool bValidDataAddress, NotMemoryLock bNotMemoryLock, bool bRead, bool bNotVectorPull)
{
    CW65Operation::Init();

    mbValidProgramAddress = bValidProgramAddress;
    mbValidDataAddress = bValidDataAddress;
    mbNotMemoryLock = bNotMemoryLock;
    mbRead = bRead;
    mbNotVectorPull = bNotVectorPull;
    mbReady = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsData(void)
{
    return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsRead(void)
{
    return mbRead;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsValidProgramAddress(void)
{
    return mbValidProgramAddress;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsValidDataAddress(void)
{
    return mbValidDataAddress;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsNotMemoryLock(void)
{
    return mbNotMemoryLock;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsNotVectorPull(void)
{
    return mbNotVectorPull;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsReady(void)
{
    return mbReady;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DataOperation::IsFetchOpcode(void)
{
    return false;
}


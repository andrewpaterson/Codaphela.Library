#include "W65CCore.h"
#include "W65DoneInstructionIfBinary.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfBinary::Init(void)
{
	CW65Operation::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfBinary::Execute(CW65CCore* pcCPU)
{
	if (!pcCPU->IsDecimal())
	{
		pcCPU->DoneInstruction();
	}
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DoneInstructionIfBinary::IsInitialSide(void)
{
	return false;
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfBinary::Print(CChars* psz)
{
	psz->Append("DONE_If_Binary");
}


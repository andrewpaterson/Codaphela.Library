#include "W65C02InstructionFactory.h"
#include "W65C02Meta.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65C02Meta::Init(W65C02MetaTickHigh fTickHigh, W65C02MetaTickLow fTickLow, void* pvContext)
{
	InitTraces(pvContext);
	mcSYNC.Init();
	mcSOB.Init(true);

	mcPins.Init(&mcAddress, &mcData, &mcPHI2, &mcRESB, &mcRWB);
	mcPins.SetVectorPullTrace(&mcVPB);
	mcPins.SetInterruptTraces(NULL, &mcIRQB, &mcNMIB);
	mcPins.SetControlTraces(&mcMLB, &mcBE, &mcRDY);
	mcPins.SetW65C02Traces(&mcSYNC, &mcSOB);

	mcMPU.Init(&mcPins);

	mfTickHigh = fTickHigh;
	mfTickLow = fTickLow;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65C02Meta::Kill(void)
{
	mcMPU.Kill();
	mcPins.Kill();

	mcSYNC.Kill();
	mcSOB.Kill();
	KillTraces();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65C02Meta::IsResetInstruction(void)
{
	return IsInstruction(CW65C02InstructionFactory::GetInstance()->GetReset());
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65C02Meta::IsStopInstruction(void)
{
	return IsInstruction(CW65C02InstructionFactory::GetInstance()->GetInstruction(W65C02_STP_Implied));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65C02Meta::IsOpcodeFetchSignalled(void)
{
	return mcSYNC.IsHigh();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65C02Meta::LatchPhi2Low(void)
{
	//The W65C02S has no bank address.
	SetBank(0);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65C02Meta::CallTickHigh(void)
{
	mfTickHigh(this, mpvContext);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65C02Meta::CallTickLow(void)
{
	mfTickLow(this, mpvContext);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CW65C02*    CW65C02Meta::GetMPU(void)     { return &mcMPU; }
CW65CCore*  CW65C02Meta::GetCore(void)    { return &mcMPU; }
CW65MetaTrace* CW65C02Meta::GetSYNC(void)	  { return &mcSYNC; }
CW65MetaTrace* CW65C02Meta::GetSOB(void)	  { return &mcSOB; }


void CIRQVector::Init(void)
{
    CInterruptVector::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CIRQVector::GetAddress(CW65CCore* pcCPU)
{
    if (pcCPU->IsEmulation())
    {
        return 0xfffe;
    }
    else
    {
        return 0xffee;
    }
}


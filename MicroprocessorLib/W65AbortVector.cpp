void CW65AbortVector::Init(void)
{
    CW65InterruptVector::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CW65AbortVector::GetAddress(CW65CCore* pcCPU)
{
    if (pcCPU->IsEmulation())
    {
        return 0xfff8;
    }
    else
    {
        return 0xffe8;
    }
}


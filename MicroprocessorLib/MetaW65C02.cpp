#include "W65C02InstructionFactory.h"
#include "MetaW65C02.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaW65C02::Init(MetaW65C02TickHigh fTickHigh, MetaW65C02TickLow fTickLow, void* pvContext)
{
	InitTraces(pvContext);
	mcSYNC.Init();
	mcSOB.Init(true);

	mcPins.Init(&mcAddress, &mcData, &mcPHI2, &mcRESB, &mcRWB);
	mcPins.SetVectorPullTrace(&mcVPB);
	mcPins.SetInterruptTraces(NULL, &mcIRQB, &mcNMIB);
	mcPins.SetControlTraces(&mcMLB, &mcBE, &mcRDY);
	mcPins.SetW65C02Traces(&mcSYNC, &mcSOB);

	mcMPU.Init(&mcPins);

	mfTickHigh = fTickHigh;
	mfTickLow = fTickLow;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaW65C02::Kill(void)
{
	mcMPU.Kill();
	mcPins.Kill();

	mcSYNC.Kill();
	mcSOB.Kill();
	KillTraces();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMetaW65C02::IsResetInstruction(void)
{
	return IsInstruction(CW65C02InstructionFactory::GetInstance()->GetReset());
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMetaW65C02::IsStopInstruction(void)
{
	return IsInstruction(CW65C02InstructionFactory::GetInstance()->GetInstruction(W65C02_STP_Implied));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMetaW65C02::IsOpcodeFetchSignalled(void)
{
	return mcSYNC.IsHigh();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaW65C02::LatchPhi2Low(void)
{
	//The W65C02S has no bank address.
	SetBank(0);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaW65C02::CallTickHigh(void)
{
	mfTickHigh(this, mpvContext);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaW65C02::CallTickLow(void)
{
	mfTickLow(this, mpvContext);
}



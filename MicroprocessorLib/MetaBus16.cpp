#include "MetaBus16.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus16::Init(void)
{
	muiValue = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus16::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus16::Set(uint16 uiValue)
{
	muiValue = uiValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CMetaBus16::Get(void)
{
	return muiValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus16::Print(CChars* psz, bool bAppend0x)
{
	Append0x(psz, bAppend0x);
	psz->AppendHexHiLo(&muiValue, 2);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus16::Write(CTimeline* pcTimeline, uint32 uiValue)
{
	muiValue = (uint16)uiValue;
}


//////////////////////////////////////////////////////////////////////////
//
// An ideal bus has no undriven state; it keeps its value.
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus16::WriteImpedance(CTimeline* pcTimeline)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CMetaBus16::Read(CTimeline* pcTimeline)
{
	return muiValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CMetaBus16::GetWidth(void)
{
	return 16;
}


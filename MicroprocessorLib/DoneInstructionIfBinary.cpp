#include "W65CCore.h"
#include "DoneInstructionIfBinary.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfBinary::Init(void)
{
	COperation::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfBinary::Execute(CW65CCore* pcCPU)
{
	if (!pcCPU->IsDecimal())
	{
		pcCPU->DoneInstruction();
	}
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CDoneInstructionIfBinary::IsInitialSide(void)
{
	return false;
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfBinary::Print(CChars* psz)
{
	psz->Append("DONE_If_Binary");
}


//////////////////////////////////////////////////////////////////////////
uint16 CW65NMIVector::GetAddress(CW65CCore* pcCPU)
{
    if (pcCPU->IsEmulation())
    {
        return 0xfffa;
    }
    else
    {
        return 0xffea;
    }
}


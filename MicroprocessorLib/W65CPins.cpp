//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::Init(CW65MetaBus16* pcAddress, CW65MetaBus8* pcData, CW65MetaTrace* pcPHI2, CW65MetaTrace* pcRESB, CW65MetaTrace* pcRWB)
{
	mpcAddress = pcAddress;
	mpcData = pcData;
	mpcVPB = NULL;
	mpcRDY = NULL;
	mpcABORTB = NULL;
	mpcIRQB = NULL;
	mpcNMIB = NULL;
	mpcMLB = NULL;
	mpcRESB = pcRESB;
	mpcPHI2 = pcPHI2;
	mpcBE = NULL;
	mpcRWB = pcRWB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////

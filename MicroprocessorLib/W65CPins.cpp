#include "W65CPins.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::Init(CMetaBus16* pcAddress, CMetaBus8* pcData, CMetaTrace* pcPHI2, CMetaTrace* pcRESB, CMetaTrace* pcRWB)
{
	mpcAddress = pcAddress;
	mpcData = pcData;
	mpcVPB = NULL;
	mpcRDY = NULL;
	mpcABORTB = NULL;
	mpcIRQB = NULL;
	mpcNMIB = NULL;
	mpcMLB = NULL;
	mpcRESB = pcRESB;
	mpcPHI2 = pcPHI2;
	mpcBE = NULL;
	mpcRWB = pcRWB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::SetInterruptTraces(CMetaTrace* pcABORTB, CMetaTrace* pcIRQB, CMetaTrace* pcNMIB)
{
	mpcABORTB = pcABORTB;
	mpcIRQB = pcIRQB;
	mpcNMIB = pcNMIB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::SetVectorPullTrace(CMetaTrace* pcVPB)
{
	mpcVPB = pcVPB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::SetControlTraces(CMetaTrace* pcMLB, CMetaTrace* pcBE, CMetaTrace* pcRDY)
{
	mpcMLB = pcMLB;
	mpcBE = pcBE;
	mpcRDY = pcRDY;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::Kill(void)
{
	mpcAddress = NULL;
	mpcData = NULL;
	mpcVPB = NULL;
	mpcRDY = NULL;
	mpcABORTB = NULL;
	mpcIRQB = NULL;
	mpcNMIB = NULL;
	mpcMLB = NULL;
	mpcRESB = NULL;
	mpcPHI2 = NULL;
	mpcBE = NULL;
	mpcRWB = NULL;
}



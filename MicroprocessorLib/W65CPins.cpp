//////////////////////////////////////////////////////////////////////////
//
// Stops driving the data bus so memory can.  An ideal bus keeps its
// value; analog traces go undriven.
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::ReleaseData(CTimeline* pcTimeline)
{
	mpcData->WriteImpedance(pcTimeline);
}



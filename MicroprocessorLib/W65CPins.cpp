#include "W65CPins.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::Init(CLogicBus* pcAddress, CLogicBus* pcData, CLogicSignal* pcPHI2, CLogicSignal* pcRESB, CLogicSignal* pcRWB)
{
	mpcAddress = pcAddress;
	mpcData = pcData;
	mpcVPB = NULL;
	mpcRDY = NULL;
	mpcABORTB = NULL;
	mpcIRQB = NULL;
	mpcNMIB = NULL;
	mpcMLB = NULL;
	mpcRESB = pcRESB;
	mpcPHI2 = pcPHI2;
	mpcBE = NULL;
	mpcRWB = pcRWB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::SetInterruptTraces(CLogicSignal* pcABORTB, CLogicSignal* pcIRQB, CLogicSignal* pcNMIB)
{
	mpcABORTB = pcABORTB;
	mpcIRQB = pcIRQB;
	mpcNMIB = pcNMIB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::SetVectorPullTrace(CLogicSignal* pcVPB)
{
	mpcVPB = pcVPB;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::SetControlTraces(CLogicSignal* pcMLB, CLogicSignal* pcBE, CLogicSignal* pcRDY)
{
	mpcMLB = pcMLB;
	mpcBE = pcBE;
	mpcRDY = pcRDY;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65CPins::Kill(void)
{
	mpcAddress = NULL;
	mpcData = NULL;
	mpcVPB = NULL;
	mpcRDY = NULL;
	mpcABORTB = NULL;
	mpcIRQB = NULL;
	mpcNMIB = NULL;
	mpcMLB = NULL;
	mpcRESB = NULL;
	mpcPHI2 = NULL;
	mpcBE = NULL;
	mpcRWB = NULL;
}



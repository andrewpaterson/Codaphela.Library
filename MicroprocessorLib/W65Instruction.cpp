#include "W65Instruction.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65Instruction::Init(uint16 uiCode, CW65InstructionCycles* pcCycles, char* szName, char* szDescription)
{
    mszDescription.Init(szDescription);
    muiCode = uiCode;
    mszName.Init(szName);
    meAddressingMode = pcCycles->GetAddressingMode();
    mpcCycles = pcCycles;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65Instruction::Kill(void)
{
    mpcCycles->Kill();
    SafeKill(mpcCycles);

    mszName.Kill();
    mszDescription.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CW65Instruction::GetCode(void)
{
    return muiCode;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CW65Instruction::GetName(void)
{
    return mszName.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CW65Instruction::GetDescription(void)
{
    return mszDescription.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CW65InstructionCycles* CW65Instruction::GetCycles(void)
{
    return mpcCycles;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CW65BusCycle* CW65Instruction::GetBusCycle(int16 iCycle)
{
    return mpcCycles->GetBusCycle(iCycle);
}


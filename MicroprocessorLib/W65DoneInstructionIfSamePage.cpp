#include "W65CCore.h"
#include "W65DoneInstructionIfSamePage.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfSamePage::Init(void)
{
	CW65Operation::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfSamePage::Execute(CW65CCore* pcCPU)
{
	//A taken branch finishes here unless it crosses a page (emulation mode, see NoteSix).
	if (!pcCPU->NoteSix())
	{
		pcCPU->DoneInstruction();
	}
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DoneInstructionIfSamePage::IsInitialSide(void)
{
	return false;
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfSamePage::Print(CChars* psz)
{
	psz->Append("DONE_If_Same_Page");
}


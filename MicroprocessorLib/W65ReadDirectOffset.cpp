#include "W65CCore.h"
#include "W65ReadDirectOffset.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65ReadDirectOffset::Init(NotMemoryLock bNotMemoryLock)
{
	CW65DataOperation::Init(true, false, bNotMemoryLock, true, true);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65ReadDirectOffset::Execute(CW65CCore* pcCPU)
{
	//This is not the 16bit Direct Page this is 8bit direct offset D0.
	pcCPU->SetDirectOffset(pcCPU->GetIOData());
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65ReadDirectOffset::IsInitialSide(void)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65ReadDirectOffset::Print(CChars* psz)
{
	psz->Append("Read(D0)");
}


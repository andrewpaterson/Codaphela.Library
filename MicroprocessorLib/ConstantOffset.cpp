#include "W65CCore.h"
#include "ConstantOffset.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CConstantOffset::Init(int32 iOffset)
{
    Init(iOffset, false);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CConstantOffset::Init(int32 iOffset, bool bOnlyIfMemory16Bit)
{
    if (iOffset < -1 || iOffset > 3)
    {
        LOG_ERROR("Numeric Offset must be in the range -1...3.");
    }
    miOffset = iOffset;
    mbOnlyIfMemory16Bit = bOnlyIfMemory16Bit;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CConstantOffset::InitAddress(uint16 uiAddress)
{
    //A fixed address rather than an offset.
    miOffset = uiAddress;
    mbOnlyIfMemory16Bit = false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CConstantOffset::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int32 CConstantOffset::GetOffset(CW65CCore* pcCPU)
{
    if (mbOnlyIfMemory16Bit && pcCPU->IsMemory8Bit())
    {
        return 0;
    }
    return miOffset;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CConstantOffset::Print(CChars* psz)
{
    if (miOffset >= 0)
    {
        psz->Append("+");
        psz->Append(miOffset);
    }
    else
    {
        psz->Append(miOffset);
    }
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CConstantOffset::IsConstantOffset(void)
{
    return true;
}


#include "W65C816.h"
#include "DoneInstructionIfEmulation.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfEmulation::Execute(CW65C816* pcCPU)
{
	if (pcCPU->IsEmulation())
	{
		pcCPU->DoneInstruction();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CDoneInstructionIfEmulation::IsInitialSide(void)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDoneInstructionIfEmulation::Print(CChars* psz)
{
	psz->Append("DONE_If_Emulation");
}


#include "W65CCore.h"
#include "W65NoteFour.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65NoteFour::Init(bool bIndexY, bool bNextWillRead)
{
	CW65Operation::Init();

	mbIndexY = bIndexY;
	mbNextWillRead = bNextWillRead;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65NoteFour::Execute(CW65CCore* pcCPU)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65NoteFour::IsInitialSide(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65NoteFour::MustExecute(CW65CCore* pcCPU)
{
	return pcCPU->NoteFour(mbIndexY, mbNextWillRead);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65NoteFour::IsConditional(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65NoteFour::Print(CChars* psz)
{
	psz->Append("Note(4)");
}


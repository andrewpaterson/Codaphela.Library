//////////////////////////////////////////////////////////////////////////
void CW65SetProgramBank::Init(uint8 uiBank)
{
	CW65Operation::Init();
	
	muiBank = uiBank;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65SetProgramBank::Execute(CW65CCore* pcCPU)
{
    pcCPU->SetProgramAddressBank(muiBank);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65SetProgramBank::IsInitialSide(void)
{
	return false;
}



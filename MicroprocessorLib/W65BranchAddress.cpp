#include "W65CCore.h"
#include "W65BranchAddress.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65BranchAddress::Init(void)
{
	Init(BA_Origin);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65BranchAddress::Init(EBranchAddress eAddress)
{
	meAddress = eAddress;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65BranchAddress::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int32 CW65BranchAddress::GetOffset(CW65CCore* pcCPU)
{
	uint16	uiTarget;
	uint16	uiOrigin;

	uiTarget = pcCPU->GetProgramCounter()->GetOffset();
	uiOrigin = uiTarget - pcCPU->GetData8BitOffset();
	if (meAddress == BA_Origin)
	{
		return uiOrigin;
	}
	else
	{
		return (uiOrigin & 0xFF00) | (uiTarget & 0x00FF);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65BranchAddress::Print(CChars* psz)
{
	if (meAddress == BA_Origin)
	{
		psz->Append("PC-RL");
	}
	else
	{
		psz->Append("PCH-RL,PCL");
	}
}


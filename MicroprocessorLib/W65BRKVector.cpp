void CW65BRKVector::Init(void)
{
    CW65InterruptVector::Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CW65BRKVector::GetAddress(CW65CCore* pcCPU)
{
    if (pcCPU->IsEmulation())
    {
        return 0xfffe;
    }
    else
    {
        return 0xffe6;
    }
}


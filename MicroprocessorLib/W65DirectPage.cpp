#include "W65CCore.h"
#include "W65DirectPage.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DirectPage::Init(void)
{
	Init(true);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DirectPage::Init(bool bPageWrap)
{
	mbPageWrap = bPageWrap;
	mbCanPageWrap = bPageWrap;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DirectPage::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int32 CW65DirectPage::GetOffset(CW65CCore* pcCPU)
{
    return pcCPU->GetDirectPage();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DirectPage::IsPageWrapped(CW65CCore* pcCPU)
{
	//Datasheet caveat 7.2: in emulation mode with DL=00 direct addresses stay in page DH.
	//[d], [d],y and PEI pointers are not wrapped.
	return mbPageWrap && pcCPU->IsEmulation() && (GetLowByte(pcCPU->GetDirectPage()) == 0);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DirectPage::Print(CChars* psz)
{
    psz->Append("D");
}


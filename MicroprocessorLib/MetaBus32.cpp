#include "MetaBus32.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus32::Init(void)
{
	muiValue = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus32::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus32::Set(uint32 uiValue)
{
	muiValue = uiValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CMetaBus32::Get(void)
{
	return muiValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus32::Print(CChars* psz, bool bAppend0x)
{
	Append0x(psz, bAppend0x);
	psz->AppendHexHiLo(&muiValue, 4);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus32::Write(CTimeline* pcTimeline, uint32 uiValue)
{
	muiValue = (uint32)uiValue;
}


//////////////////////////////////////////////////////////////////////////
//
// An ideal bus has no undriven state; it keeps its value.
//
//////////////////////////////////////////////////////////////////////////
void CMetaBus32::WriteImpedance(CTimeline* pcTimeline)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CMetaBus32::Read(CTimeline* pcTimeline)
{
	return muiValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CMetaBus32::GetWidth(void)
{
	return 32;
}


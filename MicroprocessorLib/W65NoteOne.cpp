#include "W65CCore.h"
#include "W65NoteOne.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65NoteOne::Init(EWidthFromRegister eWidth)
{
    CW65Operation::Init();

    meWidth = eWidth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65NoteOne::Execute(CW65CCore* pcCPU)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65NoteOne::IsInitialSide(void)
{
    return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65NoteOne::MustExecute(CW65CCore* pcCPU)
{
    if (meWidth == WFR_M)
    {
        return pcCPU->IsMemory16Bit();
    }
    else if (meWidth == WFR_XY)
    {
        return pcCPU->IsIndex16Bit();
    }
    else
    {
        LOG_ERROR("Unknown Width.");
        return false;
    }
}



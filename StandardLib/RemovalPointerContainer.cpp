#include "RemovalPointerContainer.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CRemovalPointerContainer::Init(CArrayBaseObjectPtr* papcKilled, bool bFreeArray)
{
	if (!bFreeArray)
	{
		mpapcKilled = papcKilled;
	}
	else
	{
		mpapcKilled = NULL;
		mapcKilled.Init();
		mapcKilled.InsertArrayAfterEnd(papcKilled);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CRemovalPointerContainer::Kill(void)
{
	if (mpapcKilled == NULL)
	{
		mapcKilled.Kill();
	}
	mpapcKilled = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CArrayBaseObjectPtr* CRemovalPointerContainer::GetKilled(void)
{
	if (mpapcKilled == NULL)
	{
		return &mapcKilled;
	}
	else
	{
		return mpapcKilled;
	}
}


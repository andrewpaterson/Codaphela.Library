void CStackPointer::Init(void)
{
	msPointer.meType = SPT_Unknown;
	msPointer.u.pcPointer = NULL;
	mpcNext = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////

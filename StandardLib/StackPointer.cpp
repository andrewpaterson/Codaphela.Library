//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CStackPointer* CStackPointer::Remove(EStackPointerType eType, void* pvPointer, CFreeList* pcFreeList, bool* pbRemoved)
{
	//Returns the new first stack pointer.  If pvPointer is not found the list is unchanged and this is returned.

	CStackPointer*	pcNext;
	CStackPointer*	pcPrev;
	CStackPointer*	pcThis;

	pcNext = this;
	pcPrev = NULL;
	while (pcNext != NULL)
	{
		pcThis = pcNext;
		if ((pcThis->msPointer.meType == eType) && (pcThis->msPointer.u.pvPointer == pvPointer))
		{
			if (pcPrev)
			{
				pcPrev->SetNext(pcThis->mpcNext);
				pcThis->Kill();
				pcFreeList->Remove(pcThis);
				*pbRemoved = true;
				return this;
			}
			else
			{
				pcNext = mpcNext;
				pcThis->Kill();
				pcFreeList->Remove(pcThis);
				*pbRemoved = true;
				return pcNext;
			}
		}
		pcPrev = pcNext;
		pcNext = pcNext->mpcNext;
	}

	if (eType == SPT_Pointer)
	{
		gcLogger.Error2(__METHOD__, " Could not remove Stack Pointer (Pointer).", NULL);
	}
	else
	{
		gcLogger.Error2(__METHOD__, " Could not remove Stack Pointer (Collection).", NULL);
	}
	*pbRemoved = false;
	return this;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CStackPointer::RemoveAll(CFreeList* pcFreeList)
{
	CStackPointer* pcNext;
	CStackPointer* pcThis;

	pcNext = this;
	while (pcNext != NULL)
	{
		pcThis = pcNext;
		pcNext = pcNext->mpcNext;
		pcThis->Kill();
		pcFreeList->Remove(pcThis);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CStackPointer::ClearPointer(void)
{
	if (msPointer.meType == SPT_Pointer)
	{
		msPointer.u.pcPointer->UnsafeClearObject();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CStackPointer* CStackPointer::ClearPointerGetNext(CEmbeddedObject* pcPointedTo)
{
	ClearPointer();
	if (msPointer.meType == SPT_Collection)
	{
		msPointer.u.pcCollection->RemovePointerTo(pcPointedTo);
	}
	return GetNext();
}



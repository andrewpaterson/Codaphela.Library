//////////////////////////////////////////////////////////////////////////
//
// Each line of an asm statement's text (lines end at a newline or a ;).
//
//////////////////////////////////////////////////////////////////////////
void CCPPTarget::AppendAsmRoutine(CChars* pszDest, const char* szText)
{
	const char*	sz;

	pszDest->Append("\t\t");
	for (sz = szText; *sz; sz++)
	{
		if ((*sz == '\n') || (*sz == ';'))
		{
			pszDest->Append("\n\t\t");
		}
		else if (*sz != '\r')
		{
			pszDest->Append(*sz);
		}
	}
	pszDest->AppendNewLine();
}



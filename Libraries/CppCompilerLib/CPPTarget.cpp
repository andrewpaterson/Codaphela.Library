static CCPPTargetHost		gcCPPTargetHost;


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CCPPTarget* GetCPPTarget(ECPPTarget eTarget)
{
	switch (eTarget)
	{
	case CPPT_W65C816:
		return &gcCPPTargetW65C816;
	case CPPT_Host:
		return &gcCPPTargetHost;
	default:
		return &gcCPPTarget65C64;
	}
}



void CDefine::Dump(void)
{
	CChars		sz;
	size		i;
	CChars*		psz;

	sz.Init();

	if (IsInMap())
	{
		sz.Append(GetName());
	}
	else
	{
		sz.Append("*Not In Map*");
	}

	if (IsBracketed())
	{
		sz.Append('(');
		for (i = 0; i < maszArguments.NumElements(); i++)
		{
			psz = maszArguments.Get(i);
			sz.Append(psz->Text());

			if (i != maszArguments.NumElements() - 1)
			{
				sz.Append(", ");
			}
		}

		if (IsVariadic())
		{
			sz.Append("...");
		}
		sz.Append(')');
	}

	if (mcReplacement.TokenLength() > 0)
	{
		sz.Append(' ');
		mcReplacement.Print(&sz);
	}
	else
	{
		sz.AppendNewLine();
	}

	sz.Dump();
	sz.Kill();
}



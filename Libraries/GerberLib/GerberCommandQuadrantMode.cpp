#include "GerberCommandQuadrantMode.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandQuadrantMode::Init(EGerberCommandEnum eType, EGerberQuadrantMode eMode)
{
	CGerberCommand::Init(eType);
	meMode = eMode;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandQuadrantMode::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandQuadrantMode::IsQuadrantMode(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandQuadrantMode::IsSingleQuadrant(void)
{
	return meMode == GQM_Single;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandQuadrantMode::IsMultiQuadrant(void)
{
	return meMode == GQM_Multi;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
EGerberQuadrantMode CGerberCommandQuadrantMode::GetMode(void)
{
	return meMode;
}


#include "BaseLib/ConstructorCall.h"
#include "ExcellonCommands.h"


#define ADD_COMMAND(type) 	type*	pcCommand;\
pcCommand = (type*)macCommands.Add(sizeof(type)); \
New<type>(pcCommand);


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommands::Init(void)
{
	macCommands.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommands::Kill(void)
{
	size	i;
	size	uiNumElements;

	uiNumElements = macCommands.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		GetCommand(i)->Kill();
	}
	macCommands.Kill();
}



void* CMallocator::Malloc(lsize uiSize, char(** pacDebugName)[4])
{
	if (pacDebugName)
	{
		*pacDebugName = NULL;
	}
	return Malloc(uiSize);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CMallocator::FreeMultiple(CArrayVoidPtr* pav)
{
	size	uiNumElements;
	size	uiFreed;
	size	i;

	uiNumElements = pav->NumElements();
	uiFreed = 0;
	for (i = 0; i < uiNumElements; i++)
	{
		if (Free(pav->GetPtr(i)))
		{
			uiFreed++;
		}
	}
	return uiFreed;
}



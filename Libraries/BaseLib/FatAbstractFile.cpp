#include "FatAbstractFile.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CFatAbstractFile::Init(CFatFile* pcFile)
{
	CAbstractFile::Init();
	mpcFile = pcFile;
	mbOpen = false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CFatAbstractFile::Kill(void)
{
	mpcFile = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CFatAbstractFile::Open(EFileMode eFileMode)
{
	mbOpen = mpcFile != NULL;
	return mbOpen;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CFatAbstractFile::Close(void)
{
	mbOpen = false;
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
lsize CFatAbstractFile::Read(void* pvBuffer, lsize iSize, lsize iCount)
{
	lsize	uiRead;

	if ((iSize == 0) || (mpcFile->Read((uint8*)pvBuffer, iSize * iCount, &uiRead) != FAT_SUCCESS))
	{
		return 0;
	}
	return uiRead / iSize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CFatAbstractFile::Seek(filePos iOffset, EFileSeekOrigin iSeekOrigin)
{
	filePos	iPosition;

	if (iSeekOrigin == EFSO_CURRENT)
	{
		iPosition = Tell() + iOffset;
	}
	else if (iSeekOrigin == EFSO_END)
	{
		iPosition = Size() + iOffset;
	}
	else
	{
		iPosition = iOffset;
	}
	if ((iPosition < 0) || (iPosition > Size()))
	{
		return false;
	}
	return mpcFile->Seek((uint32)iPosition, FAT_SEEK_START) == FAT_SUCCESS;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
lsize CFatAbstractFile::Write(const void* pvBuffer, lsize iSize, lsize iCount)
{
	if ((iSize == 0) || (mpcFile->Write((uint8*)pvBuffer, iSize * iCount) != FAT_SUCCESS))
	{
		return 0;
	}
	return iCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
filePos CFatAbstractFile::Tell(void)
{
	return mpcFile->Tell();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CFatAbstractFile::IsOpen(void)
{
	return mbOpen;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
filePos CFatAbstractFile::Size(void)
{
	return mpcFile->Size();
}


//////////////////////////////////////////////////////////////////////////
//
// A FAT file can only be truncated at its position (CFatFile::Truncate).
//
//////////////////////////////////////////////////////////////////////////
bool CFatAbstractFile::Truncate(filePos iSize)
{
	if (!Seek(iSize, EFSO_SET))
	{
		return false;
	}
	return mpcFile->Truncate() == FAT_SUCCESS;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CFatAbstractFile::Flush(void)
{
	return mpcFile->Flush() == FAT_SUCCESS;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CFatAbstractFile::Delete(void)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
const char* CFatAbstractFile::GetFilename(void)
{
	return "";
}

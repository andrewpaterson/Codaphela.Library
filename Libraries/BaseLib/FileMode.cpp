#include "FileMode.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool IsFileModeWritable(EFileMode eFileMode)
{
	return (eFileMode == EFM_ReadWrite) || (eFileMode == EFM_Write_Create) || (eFileMode == EFM_ReadWrite_Create) || (eFileMode == EFM_Write_Replace);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool IsFileModeReadable(EFileMode eFileMode)
{
	return (eFileMode == EFM_ReadWrite) || (eFileMode == EFM_Read) || (eFileMode == EFM_ReadWrite_Create) || (eFileMode == EFM_Read_Create);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool IsFileModeReadOnly(EFileMode eFileMode)
{
	return (eFileMode == EFM_Read) || (eFileMode == EFM_Read_Create);
}


//////////////////////////////////////////////////////////////////////////
//
// The file is made if it isn't there.
//
//////////////////////////////////////////////////////////////////////////
bool IsFileModeCreate(EFileMode eFileMode)
{
	return (eFileMode == EFM_Read_Create) || (eFileMode == EFM_Write_Create) || (eFileMode == EFM_ReadWrite_Create) || (eFileMode == EFM_Write_Replace);
}


//////////////////////////////////////////////////////////////////////////
//
// The file is emptied if it is there.
//
//////////////////////////////////////////////////////////////////////////
bool IsFileModeReplace(EFileMode eFileMode)
{
	return eFileMode == EFM_Write_Replace;
}


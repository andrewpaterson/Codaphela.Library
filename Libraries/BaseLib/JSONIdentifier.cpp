#include "CPPIdentifier.h"
#include "JSONIdentifier.h"


//////////////////////////////////////////////////////////////////////////
//
// JSON identifiers are parsed as C++ identifiers are.
//
/////////////////////////////////////////////////////////////////////////
TRISTATE ParseJSONExactIdentifier(CTextParser* pcTextParser, const char* szIdentifier)
{
	return ParseCPPExactIdentifier(pcTextParser, szIdentifier);
}


//////////////////////////////////////////////////////////////////////////
//
//
/////////////////////////////////////////////////////////////////////////
TRISTATE ParseJSONIdentifier(CTextParser* pcTextParser, char* szIdentifier, size* piLength)
{
	return ParseCPPIdentifier(pcTextParser, szIdentifier, piLength);
}


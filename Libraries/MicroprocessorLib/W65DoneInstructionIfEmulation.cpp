#include "W65CCore.h"
#include "W65DoneInstructionIfEmulation.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfEmulation::Execute(CW65CCore* pcCPU)
{
	if (pcCPU->IsEmulation())
	{
		pcCPU->DoneInstruction();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65DoneInstructionIfEmulation::IsInitialSide(void)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65DoneInstructionIfEmulation::Print(CChars* psz)
{
	psz->Append("DONE_If_Emulation");
}


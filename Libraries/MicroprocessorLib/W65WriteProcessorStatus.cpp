#include "W65CCore.h"
#include "W65WriteProcessorStatus.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65WriteProcessorStatus::Init(void)
{
	Init(false);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65WriteProcessorStatus::Init(bool bBreak)
{
	CW65DataOperation::Init(false, true, true, false, true);
	mbBreak = bBreak;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65WriteProcessorStatus::Execute(CW65CCore* pcCPU)
{
    pcCPU->WriteProcessorStatus(mbBreak);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CW65WriteProcessorStatus::IsInitialSide(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CW65WriteProcessorStatus::Print(CChars* psz)
{
	psz->Append("Write(P)");
}


#ifndef __BOX_H__
#define __BOX_H__
#include "BaseLib/Float32Box.h"
#include "Shape.h"


//A box turned any way.  Its distance and gradient are exact: outside, the gradient points from the nearest point of the box;
//inside, out through the nearest face.
class CBox : public CShape
{
CONSTRUCTABLE(CBox);
DESTRUCTABLE(CBox);
public:
	SFloat32Box		msBox;

	void	Init(SFloat32Box* psBox);
	void	Class(void) override;
	void	Free(void) override;

	float32	Distance(SFloat32Vec3* psPosition) override;
	void	Gradient(SFloat32Vec3* psDest, SFloat32Vec3* psPosition) override;
	void	GetBounds(SFloat32Bounds* psDest) override;
	bool	AddMesh(CMeshEditor* pcMeshEditor, int iSegments) override;
};


#endif // __BOX_H__


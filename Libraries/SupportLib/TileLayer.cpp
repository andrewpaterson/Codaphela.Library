#include "TileMap.h"
#include "TileLayer.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileLayer::Init(CPointer pTileMap, const char* szTileType, SSizeVec2 sMapSize, SSizeVec2 sCelSize, int iIdentifier, SInt32Vec2 sPosition)
{
	PreInit();

	mpTileMap = pTileMap;
	mszTileType.Init(szTileType);
	msMapSize = sMapSize;
	msCelSize = sCelSize;
	miIdentifier = iIdentifier;
	msPosition = sPosition;

	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileLayer::Free(void)
{
	mszTileType.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileLayer::Class(void)
{
	M_Pointer(mpTileMap);
	U_String(mszTileType);
	U_Data(SSizeVec2, msMapSize);
	U_Data(SSizeVec2, msCelSize);
	U_SInt(miIdentifier);
	U_Data(SInt32Vec2, msPosition);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CTileLayer::Load(CObjectReader* pcFile)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CTileLayer::Save(CObjectWriter* pcFile)
{
	return false;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
int32 CTileLayer::GetLayerSizeX(void)
{
	return (int32)msMapSize.x;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
int32 CTileLayer::GetLayerSizeY(void)
{
	return (int32)msMapSize.y;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SSizeVec2 CTileLayer::GetCelSize(void)
{
	return msCelSize;
}


//////////////////////////////////////////////////////////////////////////
//
// The tiles stay where they are in the grid, a new size apart.
//
//////////////////////////////////////////////////////////////////////////
void CTileLayer::SetCelSize(SSizeVec2 sCelSize)
{
	msCelSize = sCelSize;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CTileLayer::IsIdentifier(int iIdentifier)
{
	return miIdentifier == iIdentifier;
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
int CTileLayer::GetIdentifier(void)
{
	return miIdentifier;
}


//////////////////////////////////////////////////////////////////////////
//
// As CBaseMap::Blit.
//
//////////////////////////////////////////////////////////////////////////
bool CTileLayer::Blit(CInt32Rect* pcViewportRect, bool bEnsureBlitters)
{
	return BlitClipped(pcViewportRect, NULL, bEnsureBlitters);
}


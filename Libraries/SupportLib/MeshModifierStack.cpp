#include "StandardLib/Objects.h"
#include "MeshModifierStack.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::Init(Ptr<CMesh> pSource)
{
	PreInit();

	maModifiers.Init();
	mpSource = pSource;
	mpOutput = NULL;
	muiChanges = 0;

	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::Free(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::Class(void)
{
	M_Embedded(maModifiers);
	M_Pointer(mpSource);
	M_Pointer(mpOutput);
	U_Size(muiChanges);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMeshModifierStack::Load(CObjectReader* pcFile)
{
	CObject::NotImplemented(__METHOD__);
	return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMeshModifierStack::Save(CObjectWriter* pcFile)
{
	CObject::NotImplemented(__METHOD__);
	return false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::ReInit(void)
{
	maModifiers.RemoveAll();
	Changed();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::AddModifier(Ptr<CMeshModifier> pModifier)
{
	maModifiers.Add(pModifier);
	Changed();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
Ptr<CMesh> CMeshModifierStack::GetSource(void) const
{
	return mpSource;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
Ptr<CMesh> CMeshModifierStack::GetOutput(void)
{
	Ptr<CMeshModifier>	pModifier;
	Ptr<CMesh>			pMesh;
	size				i;
	size				uiNumElements;

	if (mpOutput.IsNull())
	{
		if (mpSource.IsNull())
		{
			mpSource = OMalloc<CMesh>();
		}

		pMesh = mpSource;
		uiNumElements = maModifiers.NumElements();
		for (i = 0; i < uiNumElements; i++)
		{
			pModifier = maModifiers.Get(i);
			pMesh = pModifier->Modify(pMesh);
		}
		mpOutput = pMesh;
	}
	return mpOutput;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::SetOutput(Ptr<CMesh> pOutput)
{
	Changed();
	mpOutput = pOutput;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::Touch(void)
{
	Changed();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::ClearOutput(void)
{
	mpOutput = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CMeshModifierStack::NumChanges(void) const
{
	return muiChanges;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::Changed(void)
{
	mpOutput = NULL;
	muiChanges++;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeshModifierStack::Flatten(void)
{
	mpSource = GetOutput();
	ReInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeshModifierStack::NumModifiers(void)
{
	return (int)maModifiers.NumElements();
}



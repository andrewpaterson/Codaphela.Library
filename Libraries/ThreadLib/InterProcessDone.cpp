#include "InterProcessDone.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CInterProcessDone::Start(void)
{
	Create();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CInterProcessDone::IsDone(int iCount)
{
	return Get() >= iCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CInterProcessDone::Wait(int iCount, int iTimeoutMilliseconds)
{
	return WaitUntilAtLeast(iCount, iTimeoutMilliseconds);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CInterProcessDone::Stop(void)
{
	Increment();
}


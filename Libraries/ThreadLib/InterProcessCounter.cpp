#include "InterProcessCounter.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CInterProcessCounter::Init(char* szSharedMemoryName)
{
	CInterProcessFlow::Init(szSharedMemoryName);
	mpsCounter = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CInterProcessCounter::Init(char* szSharedMemoryName, char* szSharedMemoryNamePostfix)
{
	CInterProcessFlow::Init(szSharedMemoryName, szSharedMemoryNamePostfix);
	mpsCounter = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CInterProcessCounter::Kill(void)
{
	mpsCounter = NULL;
	CInterProcessFlow::Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CInterProcessCounter::Create(void)
{
	mpsCounter = (SInterProcessCounter*)mcSharedMemory.Create(sizeof(SInterProcessCounter));
	if (mpsCounter == NULL)
	{
		return false;
	}
	mpsCounter->iCount.Set(0);
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CInterProcessCounter::Open(void)
{
	mpsCounter = (SInterProcessCounter*)mcSharedMemory.Open();
	return mpsCounter != NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CInterProcessCounter::Increment(void)
{
	return mpsCounter->iCount.Increment();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CInterProcessCounter::Get(void)
{
	return mpsCounter->iCount.Get();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CInterProcessCounter::WaitUntilAtLeast(int iCount, int iTimeoutMilliseconds)
{
	return mpsCounter->iCount.WaitUntilAtLeast(iCount, iTimeoutMilliseconds);
}


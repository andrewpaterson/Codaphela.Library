//////////////////////////////////////////////////////////////////////////
void CNativeWindowFactory::Init(CMallocator* pcMallocator)
{
	mpcMallocator = pcMallocator;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CNativeWindowFactory::Class(void)
{
	U_Pointer(mpcMallocator);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CNativeWindowFactory::Free(void)
{
	mpcMallocator = NULL;
}



#include "ObjectWriter.h"
#include "ObjectReader.h"
#include "PointerContainer.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPointerContainer::Class(void)
{
	M_Pointer(mp);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPointerContainer::Init(void)
{
	PreInit();
	mp = NULL;;
	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPointerContainer::Init(CPointer& pPointer)
{
	PreInit();
	mp = pPointer;
	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPointerContainer::Init(CEmbeddedObject* pcObject)
{
	PreInit();
	mp = pcObject;
	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPointerContainer::Free(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPointerContainer::Clear(void)
{
	mp = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CEmbeddedObject* CPointerContainer::PointerObject(void)
{
	return mp.Object();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CEmbeddedObject** CPointerContainer::PointerObjectPtr(void)
{
	return mp.ObjectPtr();
}


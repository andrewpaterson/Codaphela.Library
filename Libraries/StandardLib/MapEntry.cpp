#include "ObjectWriter.h"
#include "ObjectReader.h"
#include "MapEntry.h"



//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CMapEntry::CMapEntry(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
// The implicit copy constructor would copy CObject's internal pointer
// lists, which hold the addresses of cOther's members.  Build a fresh
// entry pointing to the same key and value instead.
//
//////////////////////////////////////////////////////////////////////////
CMapEntry::CMapEntry(const CMapEntry& cOther)
{
	Init(cOther.KeyObject(), cOther.ValueObject());
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapEntry::operator = (const CMapEntry& cOther)
{
	Kill();
	Init();
	mpKey = cOther.KeyObject();
	mpValue = cOther.ValueObject();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapEntry::Class(void)
{
	M_Pointer(mpKey);
	M_Pointer(mpValue);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapEntry::Init(void)
{
	PreInit();
	PostInit();
	mpKey = NULL;;
	mpValue = NULL;;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapEntry::Init(CPointer& pKey, CPointer& pValue)
{
	PreInit();
	PostInit();
	mpKey = pKey;
	mpValue = pValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapEntry::Init(CBaseObject* pcKey, CBaseObject* pcValue)
{
	PreInit();
	PostInit();
	mpKey = pcKey;
	mpValue = pcValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapEntry::Free(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapEntry::Clear(void)
{
	mpKey = NULL;;
	mpValue = NULL;;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMapEntry::Exists(void)
{
	return mpKey.IsNotNull();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CPointer CMapEntry::Key(void)
{
	return mpKey;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CPointer CMapEntry::Value(void)
{
	return mpValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CBaseObject* CMapEntry::KeyObject(void) const
{
	return (CBaseObject*)mpKey.Object();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CBaseObject* CMapEntry::ValueObject(void) const
{
	return (CBaseObject*)mpValue.Object();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CMapEntry::ValidatePointersEmbedded(void)
{
	bool bValid;

	bValid = mpKey.Embedding() == this;
	bValid &= mpValue.Embedding() == this;
	return bValid;
}


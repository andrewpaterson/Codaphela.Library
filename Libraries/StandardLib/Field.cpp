#include "Class.h"
#include "Classes.h"
#include "Field.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CField::Init(CClass* pcFieldClass, size uiOffset, CClass* pcContainingClass, const char* szName)
{
	mpcFieldClass = pcFieldClass;
	muiOffset = uiOffset;
	mpcContainingClass = pcContainingClass;
	strcpy(GetName(), szName);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CField::Kill(void)
{
	mpcFieldClass = NULL;
	muiOffset = 0;
	mpcContainingClass = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CClasses* CField::GetClasses(void)
{
	return mpcContainingClass->GetClasses();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CField::GetName(void)
{
	return (char*)RemapSinglePointer(this, GetNameOffset());
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CClass* CField::GetClass(void)
{
	return mpcFieldClass;
}



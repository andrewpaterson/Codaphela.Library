//////////////////////////////////////////////////////////////////////////
//
// The pointers to the hollow and to each of its embedded hollows, as a
// CObject's are to it and its embedded objects.  A hollow is killed with
// pointers to an embedded hollow when the object loaded for it has fewer
// embedded objects (CObjectRemapFrom::Remap).
//
//////////////////////////////////////////////////////////////////////////
void CHollowObject::RemoveAllHeapFroms(void)
{
	size	i;
	size	uiNumEmbedded;

	CEmbeddedObject::RemoveAllHeapFroms();
	uiNumEmbedded = NumEmbedded();
	for (i = 1; i < uiNumEmbedded; i++)
	{
		GetEmbeddedObject(i)->CEmbeddedObject::RemoveAllHeapFroms();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHollowObject::RemoveAllStackFroms(void)
{
	size	i;
	size	uiNumEmbedded;

	CEmbeddedObject::RemoveAllStackFroms();
	uiNumEmbedded = NumEmbedded();
	for (i = 1; i < uiNumEmbedded; i++)
	{
		GetEmbeddedObject(i)->CEmbeddedObject::RemoveAllStackFroms();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CEmbeddedObject* CHollowObject::GetEmbeddedObject(size iIndex)
{
	if (iIndex >= muiNumEmbedded)
	{
		return NULL;
	}

	if (iIndex == 0)
	{
		return this;
	}

	return GetRemappedEmbeddedObject(iIndex);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CHollowObject::GetEmbeddedIndex(CEmbeddedObject* pcEmbedded)
{
	CHollowEmbeddedObject*	pcCurrent;
	size					i;
	size					uiNumEmbedded;

	if (pcEmbedded == this)
	{
		return 0;
	}
	else
	{
		uiNumEmbedded = NumEmbedded();
		for (i = 1; i < uiNumEmbedded; i++)
		{
			pcCurrent = (CHollowEmbeddedObject*)GetEmbeddedObject(i);
			if (pcCurrent == pcEmbedded)
			{
				return i;
			}
		}

		return ARRAY_ELEMENT_NOT_FOUND;
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CEmbeddedObject* CHollowObject::GetRemappedEmbeddedObject(size iIndex)
{
	CEmbeddedObject*	pcEmbedded;

	pcEmbedded = (CEmbeddedObject*)RemapSinglePointer(this, sizeof(CHollowObject) + ((lsize)sizeof(CHollowEmbeddedObject) * (iIndex - 1)));
	return pcEmbedded;
}



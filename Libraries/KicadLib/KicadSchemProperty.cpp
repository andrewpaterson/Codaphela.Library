#include "KicadSchemProperty.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemProperty::Init(char* szName, char* szValue)
{
	mszName.Init(szName);
	mszValue.Init(szValue);
	msPosition.Zero();
	mfAngle = 0.0;
	mbHidden = false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemProperty::Kill(void)
{
	mszValue.Kill();
	mszName.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemProperty::SetPosition(SFloat64Vec2* psPosition, float64 fAngle)
{
	msPosition = *psPosition;
	mfAngle = fAngle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemProperty::SetHidden(bool bHidden)
{
	mbHidden = bHidden;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CKicadSchemProperty::GetName(void)
{
	return mszName.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CKicadSchemProperty::GetValue(void)
{
	return mszValue.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SFloat64Vec2* CKicadSchemProperty::GetPosition(void)
{
	return &msPosition;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CKicadSchemProperty::GetAngle(void)
{
	return mfAngle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CKicadSchemProperty::IsHidden(void)
{
	return mbHidden;
}


#include "KicadSchemLabel.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLabel::Init(EKicadSchemLabelType eType, char* szText)
{
	meType = eType;
	mszText.Init(szText);
	msPosition.Zero();
	mfAngle = 0.0;
	meShape = KSLS_None;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLabel::Kill(void)
{
	mszText.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLabel::SetPosition(SFloat64Vec2* psPosition, float64 fAngle)
{
	msPosition = *psPosition;
	mfAngle = fAngle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CKicadSchemLabel::SetShape(EKicadSchemLabelShape eShape)
{
	meShape = eShape;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
EKicadSchemLabelType CKicadSchemLabel::GetType(void)
{
	return meType;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CKicadSchemLabel::GetText(void)
{
	return mszText.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
SFloat64Vec2* CKicadSchemLabel::GetPosition(void)
{
	return &msPosition;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
float64 CKicadSchemLabel::GetAngle(void)
{
	return mfAngle;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
EKicadSchemLabelShape CKicadSchemLabel::GetShape(void)
{
	return meShape;
}


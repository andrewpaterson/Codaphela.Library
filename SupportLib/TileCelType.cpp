#include "TileCelType.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileCelType::Init(char cPattern, int iCelType)
{
	maiCelTypes.Init();
	maiCelTypes.Add(iCelType);
	mcPattern = cPattern;
	mbNot = false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileCelType::Init(char cPattern, bool bNot)
{
	maiCelTypes.Init();
	mcPattern = cPattern;
	mbNot = bNot;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileCelType::Kill(void)
{
	maiCelTypes.Kill();
	mcPattern = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileCelType::AddCelType(int iCelType)
{
	maiCelTypes.Add(iCelType);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTileCelType::IsPattern(char cPattern)
{
	return mcPattern == cPattern;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTileCelType::IsNegative(void)
{
	return mbNot;
}


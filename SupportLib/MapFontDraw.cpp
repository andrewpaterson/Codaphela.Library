#include "StandardLib/ObjectWriter.h"
#include "StandardLib/ObjectReader.h"
#include "MapFontDraw.h"


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::Init(Ptr<CSpriteMap> pMap)
{
	Init(pMap, NULL);
}


//////////////////////////////////////////////////////////////////////////
//
// Glyphs are placed as sprites in pMap and lines drawn with the text are
// put in pGeometryMap.
//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::Init(Ptr<CSpriteMap> pMap, Ptr<CGeometryMap> pGeometryMap)
{
	PreInit();

	CBaseFontDraw::Init();
	mpMap = pMap;
	mpGeometryMap = pGeometryMap;

	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::Class(void)
{
	M_Pointer(mpMap);
	M_Pointer(mpGeometryMap);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::Free(void)
{
	CBaseFontDraw::Free();
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CMapFontDraw::Save(CObjectWriter* pcFile)
{
	return CBaseFontDraw::Save(pcFile);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
bool CMapFontDraw::Load(CObjectReader* pcFile)
{
	return CBaseFontDraw::Load(pcFile);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::Begin(void)
{
	mpMap->BeginChange();
	mpMap->Clear();
	if (mpGeometryMap.IsNotNull())
	{
		mpGeometryMap->Clear();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::Rectangle(int32 x, int32 y, int32 iWidth, int32 iHeight, ARGB32 sColour)
{
	if (mpGeometryMap.IsNotNull())
	{
		mpGeometryMap->AddRectangle(x, y, iWidth, iHeight, sColour);
	}
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::Place(Ptr<CGlyph> pGlyph, int32 x, int32 y)
{
	Ptr<CImageCel>	pCel;
	Ptr<CSprite>	pSprite;
	
	pCel = pGlyph->GetCel();

	pSprite = OMalloc<CSprite>(pCel, x, y);
	mpMap->AddSprite(pSprite);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CMapFontDraw::End(void)
{
	mpMap->EndChange();
}


//////////////////////////////////////////////////////////////////////////
void CImageModifierStack::Init(Ptr<CImage> pImage)
{
	PreInit();

	mpImage = pImage;
	maModifiers.Init();

	PostInit();
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CImageModifierStack::Class(void)
{
	M_Embedded(maModifiers);
	M_Pointer(mpImage);
}

//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CImageModifierStack::Free(void)
{
}


void CTileGridSource::Init(char* szConstantName, Ptr<CImage> pImage)
{
	PreInit();
	mszConstantName = szConstantName;
	mpImage = pImage;
	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileGridSource::Free(void)
{
	mszConstantName = NULL;
}



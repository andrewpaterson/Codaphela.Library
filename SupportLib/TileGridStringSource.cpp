//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTileGridStringSource::Matches(CTileColourSource* pcTilePointSource, int x, int y)
{
	char c;

	if (!msSize.Contains(x, y))
	{
		return false;
	}

	c = maszStrings.GetCharAt(x, y);
	
	return pcTilePointSource->Matches(&c);
}


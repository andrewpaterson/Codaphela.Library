void CSoundModifierStack::Init(Ptr<CSound> pSound)
{
	PreInit();

	mpSound = pSound;
	maModifiers.Init();

	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CSoundModifierStack::Class(void)
{
	M_Embedded(maModifiers);
	M_Pointer(mpSound);
}



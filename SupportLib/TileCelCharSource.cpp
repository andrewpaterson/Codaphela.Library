#include "TileCelCharSource.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileCelCharSource::Init(char c)
{
	mc = c;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileCelCharSource::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileCelCharSource::Print(CChars* psz)
{
	psz->Append(mc);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char CTileCelCharSource::GetChar(void)
{
	return mc;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTileCelCharSource::Matches(void* pvData)
{
	char*		pcPixel;

	pcPixel = (char*)pvData;
	return mc == *pcPixel;
}


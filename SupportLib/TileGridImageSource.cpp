void CTileGridImageSource::Init(char* szConstantName, Ptr<CImage> pImage)
{
	PreInit();

	CTileGridSource::Init(szConstantName);
	mpImage = pImage;
	mpcAccessor = NULL;

	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileGridImageSource::Free(void)
{
	CTileGridSource::Free();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileGridImageSource::Class(void)
{
	CTileGridSource::Class();
	M_Pointer(mpImage);
	U_Pointer(mpcAccessor);
}



{
	return mpImage->GetDimension();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTileGridImageSource::StartGeneration(void)
{
	mpcAccessor = CImageAccessorCreator::Create(&mpImage, PT_uint8, IMAGE_DIFFUSE_RED, IMAGE_DIFFUSE_GREEN, IMAGE_DIFFUSE_BLUE, CHANNEL_STOP);
	if (mpcAccessor == NULL)
	{
		return gcLogger.Error2(__METHOD__, " Could not access the RGB channels of tile grid source [", mszConstantName, "].", NULL);
	}
	return true;
}



//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTileGridImageSource::StopGeneration(void)
{
	if (mpcAccessor)
	{
		mpcAccessor->Kill();
	}
	mpcAccessor = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
ARGB32 CTileGridImageSource::GetColour(int x, int y)
{
	uint8* puiPixel;

	puiPixel = (uint8*)mpcAccessor->Get(x, y);
	return Set32BitColour(puiPixel[0], puiPixel[1], puiPixel[2]);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTileGridImageSource::Matches(CTileCelSource* pcTileCelSource, int x, int y)
{
	void*	pvData;

	if (!mpcAccessor->IsValid(x, y))
	{
		return false;
	}

	pvData = mpcAccessor->Get(x, y);
	
	return pcTileCelSource->Matches(pvData);
}


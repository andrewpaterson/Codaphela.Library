//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTestNamedObjectWithEmbedded::Init(int iX, int iY, int iName1, int iName2, CPointer pObject, Ptr<CTestNamedObjectSmall> pSmall)
{
	PreInit();
	miX = iX;
	miY = iY;
	mNamedTest1.Init(iName1);
	mNamedTest2.Init(iName2);
	mpObject = pObject;
	mpSmall = pSmall;
	mpvUnmanaged = NULL;
	miUnmagedSize = 0;
	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTestNamedObjectWithEmbedded::Class(void)
{
	M_Pointer(mpObject);
	M_Pointer(mpSmall);
	M_Embedded(mNamedTest1);
	M_Embedded(mNamedTest2);
	U_Int32(miX);
	U_Int32(miY);
	U_UInt16(miUnmagedSize);
	U_Pointer(mpvUnmanaged);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTestNamedObjectWithEmbedded::Free(void)
{
	SafeFree(mpvUnmanaged);
	miUnmagedSize = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CTestNamedObjectWithEmbedded::Load(CObjectReader* pcFile)
{
	//mpvUnmanaged isn't saved (it loads NULL) so the size saved with it means nothing.
	miUnmagedSize = 0;
	return true;
}


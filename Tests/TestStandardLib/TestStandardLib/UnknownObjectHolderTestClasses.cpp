//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CObjectWithUnknown::AllocateUnknown(STestObjectFreedNotifier* psFreedNotifier)
{
	mpcHolder = NewMalloc<CUnknownObjectHolder>();
	mpcHolder->Init(psFreedNotifier);
}


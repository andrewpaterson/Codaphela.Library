#include "StandardLib/Objects.h"
#include "UnknownObjectHolderTestClasses.h"


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CUnknownObjectHolder::Init(STestObjectFreedNotifier* psKilledNotifier)
{
	Ptr<CTestObject>	pTestObject;

	pTestObject = OMalloc<CTestObject>();
	mpcTestObject = gcObjects.AddFreeObject<CTestObject>(pTestObject);
	mpsFreedNotifier = psKilledNotifier;
	if (mpsFreedNotifier)
	{
		mpsFreedNotifier->bFreed = false;
	}
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CUnknownObjectHolder::Kill(void)
{
	gcObjects.RemoveFreeObject(mpcTestObject);
	mpcTestObject = NULL;
	if (mpsFreedNotifier)
	{
		mpsFreedNotifier->bFreed = true;
	}
	CUnknown::Kill();
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CObjectWithUnknown::Init(STestObjectFreedNotifier* psKilledNotifier)
{
	PreInit();
	mpsFreedNotifier = psKilledNotifier;
	if (mpsFreedNotifier)
	{
		mpsFreedNotifier->bFreed = false;
	}
	mpcHolder = NULL;
	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CObjectWithUnknown::Class(void)
{
	U_Pointer(mpcHolder);
	U_Pointer(mpsFreedNotifier);
}


//////////////////////////////////////////////////////////////////////////
//																		//
//																		//
//////////////////////////////////////////////////////////////////////////
void CObjectWithUnknown::Free(void)
{
	SafeKill(mpcHolder);
	if (mpsFreedNotifier)
	{
		mpsFreedNotifier->bFreed = true;
	}
}



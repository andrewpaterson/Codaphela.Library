#include "StandardLib/ClassDefines.h"
#include "WindowLib/Canvas.h"
#include "BoxFillCanvasDraw.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBoxFillCanvasDraw::Init(ARGB32 sColour)
{
	PreInit();
	CCanvasDraw::Init();
	msColour = sColour;
	mbCanDrawPart = true;
	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBoxFillCanvasDraw::Class(void)
{
	CCanvasDraw::Class();
	U_UInt32(msColour);
	U_Bool(mbCanDrawPart);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CBoxFillCanvasDraw::Draw(Ptr<CCanvas> pCanvas)
{
	CInt32Rect	cRect;

	cRect.Init(0, 0, pCanvas->GetActualSize().x - 1, pCanvas->GetActualSize().y - 1);
	pCanvas->DrawBox(&cRect, true, msColour);
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBoxFillCanvasDraw::SetColour(ARGB32 sColour)
{
	msColour = sColour;
}


//////////////////////////////////////////////////////////////////////////
//
// It only fills with DrawBox, which keeps to the paint clip.
//
//////////////////////////////////////////////////////////////////////////
bool CBoxFillCanvasDraw::CanDrawPart(void)
{
	return mbCanDrawPart;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBoxFillCanvasDraw::SetCanDrawPart(bool bCanDrawPart)
{
	mbCanDrawPart = bCanDrawPart;
}


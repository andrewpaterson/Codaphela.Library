#include "GerberCommandApertureDefine.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandApertureDefine::Init(uint32 uiDCode, size iTemplateLength)
{
	CGerberCommand::Init(GC_AD);
	muiDCode = uiDCode;
	mszTemplate.InitLength(iTemplateLength);
	macParameters.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandApertureDefine::Kill(void)
{
	macParameters.Kill();
	mszTemplate.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandApertureDefine::IsApertureDefine(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CGerberCommandApertureDefine::GetDCode(void)
{
	return muiDCode;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CGerberCommandApertureDefine::TemplateText(void)
{
	return mszTemplate.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberCommandApertureDefine::AddParameter(CNumber* pcParameter)
{
	CNumber*	pcNumber;

	pcNumber = macParameters.Add();
	pcNumber->Init(pcParameter);
	return pcNumber;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CGerberCommandApertureDefine::NumParameters(void)
{
	return macParameters.NumElements();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberCommandApertureDefine::GetParameter(size uiIndex)
{
	return macParameters.Get(uiIndex);
}


#include "GerberAperture.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberAperture::Init(uint32 uiDCode, EGerberApertureType eType)
{
	muiDCode = uiDCode;
	meType = eType;
	macParameters.Init();
	mpcMacro = NULL;
	mcPrimitives.Init();
	mpcBlock = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberAperture::Kill(void)
{
	mpcBlock = NULL;
	mcPrimitives.Kill();
	mpcMacro = NULL;
	macParameters.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberAperture::AddParameter(CNumber* pcParameter)
{
	CNumber*	pcNumber;

	pcNumber = macParameters.Add();
	pcNumber->Init(pcParameter);
	return pcNumber;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberAperture::SetMacro(CGerberCommandApertureMacro* pcMacro)
{
	mpcMacro = pcMacro;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberAperture::SetBlock(CGerberCommandApertureBlock* pcBlock)
{
	mpcBlock = pcBlock;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CGerberAperture::GetDCode(void)
{
	return muiDCode;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
EGerberApertureType CGerberAperture::GetType(void)
{
	return meType;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberAperture::IsType(EGerberApertureType eType)
{
	return meType == eType;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberAperture::IsSolidCircle(void)
{
	//The only aperture allowed for draws and arcs.  2.4
	return (meType == GAT_Circle) && (macParameters.NumElements() == 1);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CGerberAperture::NumParameters(void)
{
	return macParameters.NumElements();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberAperture::GetParameter(size uiIndex)
{
	return macParameters.Get(uiIndex);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberCommandApertureMacro* CGerberAperture::GetMacro(void)
{
	return mpcMacro;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberEvaluatedPrimitives* CGerberAperture::GetPrimitives(void)
{
	return &mcPrimitives;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberCommandApertureBlock* CGerberAperture::GetBlock(void)
{
	return mpcBlock;
}


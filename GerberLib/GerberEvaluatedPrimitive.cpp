#include "GerberEvaluatedPrimitive.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberEvaluatedPrimitive::Init(EGerberApertureMacroPrimitive ePrimitive)
{
	mePrimitive = ePrimitive;
	macValues.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberEvaluatedPrimitive::Kill(void)
{
	macValues.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberEvaluatedPrimitive::AddValue(void)
{
	CNumber*	pcValue;

	pcValue = macValues.Add();
	pcValue->Zero();
	return pcValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
EGerberApertureMacroPrimitive CGerberEvaluatedPrimitive::GetPrimitive(void)
{
	return mePrimitive;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberEvaluatedPrimitive::IsPrimitive(EGerberApertureMacroPrimitive ePrimitive)
{
	return mePrimitive == ePrimitive;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CGerberEvaluatedPrimitive::NumValues(void)
{
	return macValues.NumElements();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberEvaluatedPrimitive::GetValue(size uiIndex)
{
	return macValues.Get(uiIndex);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberEvaluatedPrimitives::Init(void)
{
	macPrimitives.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberEvaluatedPrimitives::Kill(void)
{
	size	i;
	size	uiNumElements;

	uiNumElements = macPrimitives.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		macPrimitives.Get(i)->Kill();
	}
	macPrimitives.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberEvaluatedPrimitive* CGerberEvaluatedPrimitives::Add(EGerberApertureMacroPrimitive ePrimitive)
{
	CGerberEvaluatedPrimitive*	pcPrimitive;

	pcPrimitive = macPrimitives.Add();
	pcPrimitive->Init(ePrimitive);
	return pcPrimitive;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CGerberEvaluatedPrimitives::NumPrimitives(void)
{
	return macPrimitives.NumElements();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberEvaluatedPrimitive* CGerberEvaluatedPrimitives::GetPrimitive(size uiIndex)
{
	return macPrimitives.Get(uiIndex);
}


#include "GerberCommandOperation.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandOperation::Init(EGerberCommandEnum eType)
{
	CGerberCommand::Init(eType);
	mcX.Zero();
	mcY.Zero();
	mcI.Zero();
	mcJ.Zero();
	mbX = false;
	mbY = false;
	mbI = false;
	mbJ = false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandOperation::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandOperation::IsOperation(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandOperation::IsPlot(void)
{
	return meType == GC_D01;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandOperation::IsMove(void)
{
	return meType == GC_D02;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandOperation::IsFlash(void)
{
	return meType == GC_D03;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandOperation::SetX(CNumber* pcX)
{
	mcX.Init(pcX);
	mbX = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandOperation::SetY(CNumber* pcY)
{
	mcY.Init(pcY);
	mbY = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandOperation::SetI(CNumber* pcI)
{
	mcI.Init(pcI);
	mbI = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandOperation::SetJ(CNumber* pcJ)
{
	mcJ.Init(pcJ);
	mbJ = true;
}



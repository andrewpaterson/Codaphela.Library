#include "BaseLib/ConstructorCall.h"
#include "BaseLib/PointerFunctions.h"
#include "GerberCommands.h"
#include "GerberCommandCompound.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandCompound::Init(EGerberCommandEnum eType)
{
	CGerberCommand::Init(eType);
	mpcCommands = NewMalloc<CGerberCommands>();
	mpcCommands->Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandCompound::Kill(void)
{
	SafeKill(mpcCommands);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandCompound::IsCompound(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberCommands* CGerberCommandCompound::GetCommands(void)
{
	return mpcCommands;
}


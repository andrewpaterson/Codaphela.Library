#include "GerberApertures.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberApertures::Init(void)
{
	macApertures.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberApertures::Kill(void)
{
	size	i;
	size	uiNumElements;

	uiNumElements = macApertures.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		GetAperture(i)->Kill();
	}
	macApertures.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberAperture* CGerberApertures::Add(uint32 uiDCode, EGerberApertureType eType)
{
	CGerberAperture*	pcAperture;

	if (Get(uiDCode) != NULL)
	{
		return NULL;
	}

	pcAperture = (CGerberAperture*)macApertures.Add(sizeof(CGerberAperture));
	pcAperture->Init(uiDCode, eType);
	return pcAperture;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberAperture* CGerberApertures::Get(uint32 uiDCode)
{
	size				i;
	size				uiNumElements;
	CGerberAperture*	pcAperture;

	uiNumElements = macApertures.NumElements();
	for (i = 0; i < uiNumElements; i++)
	{
		pcAperture = GetAperture(i);
		if (pcAperture->GetDCode() == uiDCode)
		{
			return pcAperture;
		}
	}
	return NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CGerberApertures::NumApertures(void)
{
	return macApertures.NumElements();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberAperture* CGerberApertures::GetAperture(size uiIndex)
{
	return (CGerberAperture*)macApertures.Get(uiIndex);
}


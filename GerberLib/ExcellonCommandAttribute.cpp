#include "ExcellonCommandAttribute.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandAttribute::Init(EExcellonCommandEnum eType, const char* szName, size uiLength)
{
	CExcellonCommand::Init(eType);
	mszName.Init(szName, 0, uiLength);
	maszValues.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandAttribute::Kill(void)
{
	maszValues.Kill();
	mszName.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandAttribute::AddValue(const char* szValue, size uiLength)
{
	CChars*	psz;

	psz = maszValues.AddLength(uiLength);
	memcpy(psz->Text(), szValue, uiLength);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CExcellonCommandAttribute::NameText(void)
{
	return mszName.Text();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
size CExcellonCommandAttribute::NumValues(void)
{
	return maszValues.NumElements();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CExcellonCommandAttribute::ValueText(size uiIndex)
{
	return maszValues.GetText(uiIndex);
}


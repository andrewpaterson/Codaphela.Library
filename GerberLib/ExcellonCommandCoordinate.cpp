#include "ExcellonCommandCoordinate.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandCoordinate::Init(EExcellonCommandEnum eType)
{
	CExcellonCommand::Init(eType);
	mcX.Zero();
	mcY.Zero();
	mbX = false;
	mbY = false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandCoordinate::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandCoordinate::SetX(CNumber* pcX)
{
	mcX.Init(pcX);
	mbX = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandCoordinate::SetY(CNumber* pcY)
{
	mcY.Init(pcY);
	mbY = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CExcellonCommandCoordinate::HasX(void)
{
	return mbX;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CExcellonCommandCoordinate::HasY(void)
{
	return mbY;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CExcellonCommandCoordinate::GetX(void)
{
	return &mcX;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CExcellonCommandCoordinate::GetY(void)
{
	return &mcY;
}


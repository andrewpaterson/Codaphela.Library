#include "ExcellonCommandSlot.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandSlot::Init(void)
{
	CExcellonCommand::Init(EC_Slot);
	mcStartX.Zero();
	mcStartY.Zero();
	mcEndX.Zero();
	mcEndY.Zero();
	mbStartX = false;
	mbStartY = false;
	mbEndX = false;
	mbEndY = false;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandSlot::Kill(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandSlot::SetStartX(CNumber* pcX)
{
	mcStartX.Init(pcX);
	mbStartX = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandSlot::SetStartY(CNumber* pcY)
{
	mcStartY.Init(pcY);
	mbStartY = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandSlot::SetEndX(CNumber* pcX)
{
	mcEndX.Init(pcX);
	mbEndX = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandSlot::SetEndY(CNumber* pcY)
{
	mcEndY.Init(pcY);
	mbEndY = true;
}



#include "GerberCommandStepAndRepeat.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberCommandStepAndRepeat::Init(uint32 uiXRepeats, uint32 uiYRepeats, CNumber* pcXStep, CNumber* pcYStep)
{
	CGerberCommandCompound::Init(GC_SR);
	muiXRepeats = uiXRepeats;
	muiYRepeats = uiYRepeats;
	mcXStep.Init(pcXStep);
	mcYStep.Init(pcYStep);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberCommandStepAndRepeat::IsStepAndRepeat(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CGerberCommandStepAndRepeat::GetXRepeats(void)
{
	return muiXRepeats;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CGerberCommandStepAndRepeat::GetYRepeats(void)
{
	return muiYRepeats;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberCommandStepAndRepeat::GetXStep(void)
{
	return &mcXStep;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CNumber* CGerberCommandStepAndRepeat::GetYStep(void)
{
	return &mcYStep;
}


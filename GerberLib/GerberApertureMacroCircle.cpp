#include "BaseLib/Logger.h"
#include "GerberMacroVariables.h"
#include "GerberEvaluatedPrimitive.h"
#include "GerberApertureMacroCircle.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberApertureMacroCircle::Init(CCalculatorSymbols* pcSymbols, bool bSkipWhitespace, bool bUseUserError)
{
	CGerberApertureMacro::Init(GAMP_Circle);
	mcExposure.Init(pcSymbols, bSkipWhitespace, bUseUserError);
	mcDiameter.Init(pcSymbols, bSkipWhitespace, bUseUserError);
	mcCenter.Init(pcSymbols, bSkipWhitespace, bUseUserError);
	mcRotation.Init(pcSymbols, bSkipWhitespace, bUseUserError);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CGerberApertureMacroCircle::Kill(void)
{
	mcRotation.Kill();
	mcCenter.Kill();
	mcDiameter.Kill();
	mcExposure.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberExpression* CGerberApertureMacroCircle::GetExposure(void)
{
	return &mcExposure;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberExpression* CGerberApertureMacroCircle::GetDiameter(void)
{
	return &mcDiameter;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberExpression* CGerberApertureMacroCircle::GetCenterX(void)
{
	return mcCenter.GetX();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberExpression* CGerberApertureMacroCircle::GetCenterY(void)
{
	return mcCenter.GetY();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CGerberExpression* CGerberApertureMacroCircle::GetRotation(void)
{
	return &mcRotation;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberApertureMacroCircle::IsCircle(void)
{
	return true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CGerberApertureMacroCircle::Evaluate(CGerberMacroVariables* pcVariables, CGerberEvaluatedPrimitives* pcPrimitives)
{
	CGerberEvaluatedPrimitive*	pcPrimitive;

	pcPrimitive = pcPrimitives->Add(GAMP_Circle);
	return EvaluateExposure(&mcExposure, pcVariables, pcPrimitive) &&
		   EvaluateExpression(&mcDiameter, pcVariables, pcPrimitive) &&
		   EvaluateExpression(mcCenter.GetX(), pcVariables, pcPrimitive) &&
		   EvaluateExpression(mcCenter.GetY(), pcVariables, pcPrimitive) &&
		   EvaluateExpression(&mcRotation, pcVariables, pcPrimitive);
}


#include "ExcellonCommandComment.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandComment::Init(const char* szComment, size uiLength)
{
	CExcellonCommand::Init(EC_Comment);
	mszComment.Init(szComment, 0, uiLength);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CExcellonCommandComment::Kill(void)
{
	mszComment.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CExcellonCommandComment::Text(void)
{
	return mszComment.Text();
}

